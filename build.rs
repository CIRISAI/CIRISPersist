//! v62.0.0 (WASM_UEFI_READINESS P6) — embed the migration files.
//!
//! Persist applies its own migrations (`src/store/migration_runner.rs`);
//! refinery's runner stamped `applied_on` with `OffsetDateTime::now_utc()`,
//! which panics on wasm32-unknown-unknown. This writes the file list the
//! runner reads: `(stem, include_str!(file))` per `V{n}__{name}.sql`, in
//! file-name order (refinery's embed order), one list per dialect. Only std:
//! nothing here may differ between hosts.

use std::path::Path;

fn list(dir: &Path) -> Vec<(String, String)> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(dir).unwrap_or_else(|e| panic!("read {}: {e}", dir.display())) {
        let path = entry.unwrap().path();
        if path.is_dir() {
            panic!(
                "{}: persist's migrations are one flat directory per dialect",
                path.display()
            );
        }
        let file = path.file_name().unwrap().to_str().unwrap().to_owned();
        let Some(stem) = file.strip_suffix(".sql") else {
            panic!("{}: not a .sql migration", path.display());
        };
        // refinery's grammar, as persist uses it: `V` + digits + `__` + a
        // word. No `U` (unversioned) and no `.rs` migrations ship.
        let (version, name) = stem
            .strip_prefix('V')
            .and_then(|r| r.split_once("__"))
            .unwrap_or_else(|| panic!("{file}: not V{{n}}__{{name}}.sql"));
        assert!(
            !version.is_empty() && version.bytes().all(|b| b.is_ascii_digit()),
            "{file}: the version is not digits"
        );
        assert!(
            !name.is_empty() && name.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_'),
            "{file}: the name is not a word"
        );
        out.push((
            stem.to_owned(),
            path.canonicalize().unwrap().display().to_string(),
        ));
    }
    out.sort();
    out
}

fn main() {
    let root = std::env::var("CARGO_MANIFEST_DIR").unwrap();
    let mut gen = String::from("// @generated by build.rs (v62.0.0, P6). Do not edit.\n");
    for (dialect, feature, konst) in [
        ("sqlite", "sqlite", "SQLITE_MIGRATIONS"),
        ("postgres", "postgres", "POSTGRES_MIGRATIONS"),
    ] {
        let dir = Path::new(&root)
            .join("migrations")
            .join(dialect)
            .join("lens");
        println!("cargo:rerun-if-changed={}", dir.display());
        gen.push_str(&format!(
            "/// Every `migrations/{dialect}/lens/V*.sql`, as `(stem, text)`, in file-name order.\n\
             #[cfg(feature = \"{feature}\")]\n\
             pub(crate) static {konst}: &[(&str, &str)] = &[\n"
        ));
        for (stem, path) in list(&dir) {
            gen.push_str(&format!("    ({stem:?}, include_str!({path:?})),\n"));
        }
        gen.push_str("];\n");
    }
    let out = Path::new(&std::env::var("OUT_DIR").unwrap()).join("embedded_migrations.rs");
    std::fs::write(out, gen).unwrap();
    println!("cargo:rerun-if-changed=build.rs");
}
