fn text(s: &str) -> Value {
    Value::Text(s.to_owned())
}

/// A deterministic map: entries sorted by their keys' encodings.
fn map(mut m: Vec<(&str, Value)>) -> Value {
    m.sort_by_key(|(k, _)| cde::encode(&text(k)));
    Value::Map(m.into_iter().map(|(k, v)| (text(k), v)).collect())
}

/// A deterministic map keyed by owned text.
fn map_owned(mut m: Vec<(String, Value)>) -> Value {
    m.sort_by_key(|(k, _)| cde::encode(&text(k)));
    Value::Map(m.into_iter().map(|(k, v)| (Value::Text(k), v)).collect())
}

/// A CBOR set: members sorted by their encodings.
fn set(mut xs: Vec<Value>) -> Value {
    xs.sort_by_key(cde::encode);
    Value::Array(xs)
}

fn text_set(xs: &[&str]) -> Value {
    set(xs.iter().map(|x| text(x)).collect())
}

/// `n` bytes derived from a label and a seed (SHA-256 in counter mode).
fn derived(label: &[u8], seed: u8, n: usize) -> Vec<u8> {
    let mut out = Vec::with_capacity(n);
    let mut ctr = 0u32;
    while out.len() < n {
        let mut h = sha2::Sha256::new();
        h.update(b"ciris-test-ceremony-v2\0");
        h.update(label);
        h.update([seed]);
        h.update(ctr.to_be_bytes());
        out.extend_from_slice(&h.finalize());
        ctr += 1;
    }
    out.truncate(n);
    out
}

fn sha256(b: &[u8]) -> [u8; 32] {
    sha2::Sha256::digest(b).into()
}

/// The Reticulum destination hash (CC 3.3.6.3).
fn rns_destination_hash(x: &[u8], e: &[u8], app: &str, aspects: &[&str]) -> Vec<u8> {
    let mut name = app.to_owned();
    for a in aspects {
        name.push('.');
        name.push_str(a);
    }
    let nh = &sha256(name.as_bytes())[..10];
    let mut xe = x.to_vec();
    xe.extend_from_slice(e);
    let ih = &sha256(&xe)[..16];
    let mut both = nh.to_vec();
    both.extend_from_slice(ih);
    sha256(&both)[..16].to_vec()
}

fn sign_row(k: &CompositeSigningKey, sub: &str, family: &str, payload: &Value) -> NamedRow {
    let iss = identity_ref(&thumbprint(k.public_key()));
    sign_row_as(k, &iss, sub, family, payload)
}

/// A row signed by `k` under the identity `iss` (a holder's later key or
/// its recovery key speaks for the holder's identity).
fn sign_row_as(
    k: &CompositeSigningKey,
    iss: &str,
    sub: &str,
    family: &str,
    payload: &Value,
) -> NamedRow {
    NamedRow::of(
        sign_row_statement(k, iss, sub, ROW_TYPE, family, payload, vec![])
            .expect("a fixture key signs"),
    )
}

fn holder_chain(seed: u8) -> Vec<Vec<u8>> {
    chain_of(HOLDER_CHAINS_HEX, seed)
}

fn chain_of(table: [(u8, [&str; 2]); 7], seed: u8) -> Vec<Vec<u8>> {
    for (n, chain) in table {
        if n == seed {
            return chain
                .iter()
                .map(|h| hex::decode(h).expect("a chain is hex"))
                .collect();
        }
    }
    panic!("no custody chain for holder seed {seed} (1..=7)");
}

fn mint_holder(seed: u8, t0_ms: u64) -> HolderV2 {
    let iref = identity_ref_of(seed);
    let record = holder_record(&iref, &test_key(seed), holder_chain(seed), t0_ms);
    let recovery_seed = seed + RECOVERY_SEED_OFFSET;
    HolderV2 {
        seed,
        holder_seed: seed,
        recovery_seed,
        kid: kid_of(seed),
        identity_ref: iref,
        record,
        recovery_commitment: recovery_commitment(&[test_key(recovery_seed).public_key().clone()]),
    }
}

/// A holder's `key:record` for `key`, authored and issued under the
/// holder's identity `iref`, signed by `key`, carrying `chain`.
fn holder_record(iref: &str, key: &CompositeSigningKey, chain: Vec<Vec<u8>>, at: u64) -> NamedRow {
    let evidence = map(vec![
        ("hardware_class", text(HARDWARE_CLASS)),
        ("pq_custody", text(PQ_CUSTODY)),
        (
            "chain",
            Value::Array(chain.into_iter().map(Value::Bytes).collect()),
        ),
    ]);
    holder_record_with_evidence(iref, key, evidence, at)
}

/// A holder's `key:record` as [`holder_record`], carrying `evidence` as its
/// `attestation_evidence` verbatim (whatever its shape).
fn holder_record_with_evidence(
    iref: &str,
    key: &CompositeSigningKey,
    evidence: Value,
    at: u64,
) -> NamedRow {
    let payload = map(vec![
        ("key", cose_key(key.public_key())),
        ("author", text(iref)),
        ("asserted_at", Value::Uint(at)),
        ("identity_type", text_set(&["accord_holder"])),
        ("attestation_evidence", evidence),
    ]);
    sign_row_as(key, iref, iref, KEY_RECORD_FAMILY, &payload)
}

/// A recovery key's own record: authored under the holder's identity,
/// signed by the recovery key (CC 4.2.6; Verify's `recovery_key_record`).
fn recovery_key_record(iref: &str, rk: &CompositeSigningKey, at: u64) -> NamedRow {
    let payload = map(vec![
        ("key", cose_key(rk.public_key())),
        ("author", text(iref)),
        ("asserted_at", Value::Uint(at)),
        ("identity_type", text_set(&["accord_holder"])),
    ]);
    sign_row_as(rk, iref, iref, KEY_RECORD_FAMILY, &payload)
}

fn xwing_key(label: &[u8], seed: u8) -> [u8; XWING_PUBKEY_LEN] {
    <[u8; XWING_PUBKEY_LEN]>::try_from(derived(label, seed, XWING_PUBKEY_LEN).as_slice())
        .expect("derived to length")
}

fn mint_seat(seed: u8, t0_ms: u64) -> SeatV2 {
    let k = test_key(seed);
    let kid = thumbprint(k.public_key());
    let iref = identity_ref(&kid);
    let record_payload = map(vec![
        ("key", cose_key(k.public_key())),
        ("author", text(&iref)),
        ("asserted_at", Value::Uint(t0_ms)),
        ("identity_type", text_set(&["node"])),
        ("valid_until", Value::Uint(t0_ms + YEAR_MS)),
    ]);
    let record = sign_row(&k, &iref, KEY_RECORD_FAMILY, &record_payload);
    let transit = xwing_key(b"transit", seed);
    let onion = xwing_key(b"onion", seed);
    let rx = derived(b"rns-x25519", seed, 32);
    let re = derived(b"rns-ed25519", seed, 32);
    let td = map(vec![
        ("reticulum_x25519_pubkey", Value::Bytes(rx.clone())),
        ("reticulum_ed25519_pubkey", Value::Bytes(re.clone())),
        ("app_name", text(APP_NAME)),
        ("aspects", Value::Array(vec![text(ASPECT)])),
        (
            "destination_hash",
            Value::Bytes(rns_destination_hash(&rx, &re, APP_NAME, &[ASPECT])),
        ),
    ]);
    // CC 3.3.6 (O1's ruling): every identity:occurrence names its identity,
    // its occurrence and its device class. A seat binding is the self pair.
    let binding_payload = map(vec![
        ("identity_key_id", text(&iref)),
        ("occurrence_key_id", text(&iref)),
        ("device_class", text("server")),
        ("author", text(&iref)),
        ("asserted_at", Value::Uint(t0_ms)),
        ("transport_destination", td),
        ("transit_xwing_pubkey", Value::Bytes(transit.to_vec())),
        ("onion_hop_xwing_pubkey", Value::Bytes(onion.to_vec())),
        // X2 build fix (P1e / CC rc21): `refs.head` is REQUIRED on
        // identity:occurrence; a new identity's first bind names the genesis
        // key's own key:record row, here the seat's record.
        (
            "refs",
            map(vec![
                ("head", row_ref(&record.row_id)),
                (
                    "also",
                    map(vec![("cites", Value::Array(vec![row_ref(&record.row_id)]))]),
                ),
            ]),
        ),
    ]);
    let binding = sign_row(&k, &iref, BINDING_FAMILY, &binding_payload);
    SeatV2 {
        seed,
        kid,
        identity_ref: iref,
        record,
        binding,
        transit_xwing_pubkey: transit,
        onion_hop_xwing_pubkey: onion,
    }
}

fn check_spec(spec: &CeremonySpec) {
    assert!(!spec.holders.is_empty(), "test_ceremony_v2: no holder");
    assert!(!spec.serve_nodes.is_empty(), "test_ceremony_v2: no seat");
    for h in &spec.holders {
        assert!(
            HOLDER_SEED_RANGE.contains(h),
            "test_ceremony_v2: holder seed {h} has no custody chain (1..=7)"
        );
    }
    let recovery: BTreeSet<u8> = HOLDER_SEED_RANGE
        .flat_map(|h| {
            [
                h + RECOVERY_SEED_OFFSET,
                h + RECOVERED_SEED_OFFSET,
                h + NEXT_RECOVERY_SEED_OFFSET,
                h + SECOND_RECOVERED_SEED_OFFSET,
                h + SECOND_NEXT_RECOVERY_SEED_OFFSET,
            ]
        })
        .collect();
    for s in &spec.serve_nodes {
        assert!(
            !spec.holders.contains(s) && !recovery.contains(s),
            "test_ceremony_v2: seat seed {s} is a holder's, a recovered key's or a recovery key's"
        );
    }
}

/// The bundle payload over minted holders and seats (CC 2.6.1.11).
fn bundle_payload(
    spec: &CeremonySpec,
    version: u64,
    prev: Option<&Digest32>,
    asserted_at_ms: u64,
    holders: &[HolderV2],
    seats: &[SeatV2],
    extra_rows: &[NamedRow],
) -> Value {
    let cited: Vec<Value> = holders
        .iter()
        .map(|h| row_ref(&h.record.row_id))
        .chain(extra_rows.iter().map(|r| row_ref(&r.row_id)))
        .chain(seats.iter().map(|s| row_ref(&s.record.row_id)))
        .chain(seats.iter().map(|s| row_ref(&s.binding.row_id)))
        .collect();
    let mut refs = vec![("also", map(vec![("cites", set(cited))]))];
    if let Some(p) = prev {
        refs.push(("prev", row_ref(p)));
    }
    let commitments = map_owned(
        holders
            .iter()
            .map(|h| {
                (
                    h.identity_ref.clone(),
                    hash_digest_value(&h.recovery_commitment),
                )
            })
            .collect(),
    );
    let charter = map(vec![
        ("recovery_commitments", commitments),
        ("scope", text_set(&["infra:attest", "infra:serve"])),
        ("halt_fuse_secs", Value::Uint(86_400)),
    ]);
    map(vec![
        ("refs", map(refs)),
        ("version", Value::Uint(version)),
        ("asserted_at", Value::Uint(asserted_at_ms)),
        ("family_key_id", text(&spec.family_key_id)),
        (
            "holders",
            set(holders.iter().map(|h| text(&h.identity_ref)).collect()),
        ),
        (
            "serve_nodes",
            set(seats.iter().map(|s| text(&s.identity_ref)).collect()),
        ),
        ("charter", charter),
    ])
}

/// One signer's `ceg-genesis-bundle/2` statement over `payload`.
fn voice(k: &CompositeSigningKey, iss: &str, payload_bytes: &[u8], asserted_at_ms: u64) -> Vec<u8> {
    let kid = thumbprint(k.public_key());
    let protected = object_protected(&kid, iss, GENESIS_BUNDLE_TYP, Some(asserted_at_ms / 1000));
    let sig = k
        .sign(&sig_structure(&protected, payload_bytes))
        .expect("a fixture key signs");
    assemble(protected, payload_bytes.to_vec(), sig)
}

/// One bundle over placed parties, signed by `signers` (key, `iss`).
#[allow(clippy::too_many_arguments)]
fn assemble_bundle(
    spec: &CeremonySpec,
    version: u64,
    prev: Option<Digest32>,
    asserted_at_ms: u64,
    holders: Vec<HolderV2>,
    seats: Vec<SeatV2>,
    extra_rows: Vec<NamedRow>,
    signers: &[(CompositeSigningKey, String)],
    recovered: Option<String>,
) -> TestCeremonyV2 {
    let payload = bundle_payload(
        spec,
        version,
        prev.as_ref(),
        asserted_at_ms,
        &holders,
        &seats,
        &extra_rows,
    );
    let payload_bytes = cde::encode(&payload);
    let object_id = RowId::of_object(GENESIS_BUNDLE_TYP, None, &payload_bytes).0;
    let voices = signers
        .iter()
        .map(|(k, iss)| voice(k, iss, &payload_bytes, asserted_at_ms))
        .collect();
    TestCeremonyV2 {
        spec: spec.clone(),
        version,
        prev,
        asserted_at_ms,
        holders,
        seats,
        extra_rows,
        recovered,
        payload,
        voices,
        object_id,
    }
}

/// Mint a fresh genesis (version 1, no prev), signed by every holder.
///
/// # Panics
/// A bad spec: a holder seed outside [`HOLDER_SEED_RANGE`], no holder or
/// seat, or a seat seed that is a holder's or a recovery key's.
#[must_use]
pub fn ceremony_v2(spec: &CeremonySpec) -> TestCeremonyV2 {
    check_spec(spec);
    let holders: Vec<HolderV2> = spec
        .holders
        .iter()
        .map(|s| mint_holder(*s, spec.t0_ms))
        .collect();
    let seats: Vec<SeatV2> = spec
        .serve_nodes
        .iter()
        .map(|s| mint_seat(*s, spec.t0_ms))
        .collect();
    let signers: Vec<(CompositeSigningKey, String)> = holders
        .iter()
        .map(|h| (test_key(h.seed), h.identity_ref.clone()))
        .collect();
    assemble_bundle(
        spec,
        1,
        None,
        spec.t0_ms + DAY_MS / 2,
        holders,
        seats,
        Vec::new(),
        &signers,
        None,
    )
}

/// v62.0.0 (C4-fix2) — one holder minted otherwise than [`ceremony_v2`]
/// mints it: its composite key from these seeds (ML-DSA-65 `mldsa_seed`,
/// Ed25519 `ed25519_seed`) and its `key:record` carrying `evidence` as its
/// `attestation_evidence` verbatim. Its identity reference is its own key's;
/// its recovery commitment is still `recovery_key(seed)`'s.
#[derive(Clone, Debug)]
pub struct HolderOverride {
    /// The spec holder seed it replaces.
    pub seed: u8,
    /// The ML-DSA-65 seed of its composite key.
    pub mldsa_seed: [u8; 32],
    /// The Ed25519 seed of its composite key.
    pub ed25519_seed: [u8; 32],
    /// Its record's `attestation_evidence`.
    pub evidence: Value,
}

impl HolderOverride {
    fn key(&self) -> CompositeSigningKey {
        CompositeSigningKey::from_seeds(&self.mldsa_seed, &self.ed25519_seed)
    }
}

/// v62.0.0 (C4-fix, ceremony gap 3) — [`ceremony_v2`] with holder
/// `holder_seed`'s `key:record` carrying `evidence` as its
/// `attestation_evidence` (any shape: a real YubiKey chain, a truncated or
/// reordered one, a hex-text one). The record is still authored by the
/// holder's identity and signed by its test key, and the bundle names it
/// and is signed by every holder, so only the evidence differs from
/// [`ceremony_v2`]'s. The anchor (the holders' kids) is unchanged.
///
/// # Panics
/// As [`ceremony_v2_with_holders`].
#[must_use]
pub fn ceremony_v2_with_holder_evidence(
    spec: &CeremonySpec,
    holder_seed: u8,
    evidence: Value,
) -> TestCeremonyV2 {
    ceremony_v2_with_holders(
        spec,
        &[HolderOverride {
            seed: holder_seed,
            mldsa_seed: [holder_seed; 32],
            ed25519_seed: [holder_seed.wrapping_add(100); 32],
            evidence,
        }],
    )
}

/// v62.0.0 (C4-fix2) — [`ceremony_v2`] with each [`HolderOverride`]'s
/// holder minted from its own seeds and evidence (and signing its voice
/// with that key); every other holder and seat as [`ceremony_v2`] mints
/// them. The anchor is the holders' kids as minted.
///
/// # Panics
/// As [`ceremony_v2`]; and an override whose seed is not one of the spec's
/// holders.
#[must_use]
pub fn ceremony_v2_with_holders(
    spec: &CeremonySpec,
    overrides: &[HolderOverride],
) -> TestCeremonyV2 {
    check_spec(spec);
    for o in overrides {
        assert!(
            spec.holders.contains(&o.seed),
            "test_ceremony_v2: holder seed {} is not a holder of the spec",
            o.seed
        );
    }
    let mut holders = Vec::new();
    let mut signers: Vec<(CompositeSigningKey, String)> = Vec::new();
    for s in &spec.holders {
        match overrides.iter().find(|o| o.seed == *s) {
            Some(o) => {
                let key = o.key();
                let kid = thumbprint(key.public_key());
                let iref = identity_ref(&kid);
                let record =
                    holder_record_with_evidence(&iref, &key, o.evidence.clone(), spec.t0_ms);
                let recovery_seed = s + RECOVERY_SEED_OFFSET;
                holders.push(HolderV2 {
                    seed: *s,
                    holder_seed: *s,
                    recovery_seed,
                    kid,
                    identity_ref: iref.clone(),
                    record,
                    recovery_commitment: recovery_commitment(&[test_key(recovery_seed)
                        .public_key()
                        .clone()]),
                });
                signers.push((key, iref));
            }
            None => {
                let h = mint_holder(*s, spec.t0_ms);
                signers.push((test_key(h.seed), h.identity_ref.clone()));
                holders.push(h);
            }
        }
    }
    let seats: Vec<SeatV2> = spec
        .serve_nodes
        .iter()
        .map(|s| mint_seat(*s, spec.t0_ms))
        .collect();
    assemble_bundle(
        spec,
        1,
        None,
        spec.t0_ms + DAY_MS / 2,
        holders,
        seats,
        Vec::new(),
        &signers,
        None,
    )
}

/// Mint a later bundle over `prev` (CC 5.3.4): `holders` and `serve_nodes`
/// are the new sets, by holder / seat seed, and `signers` the holder seeds
/// whose voices it carries. A party `prev` seats is carried as `prev` seats
/// it (a recovered holder keeps its re-seated key and commitment); a new one
/// is minted at prev's `t0`. Each signer signs with the key it holds now,
/// under its identity. The reader judges the count against prev's holders
/// (a strict majority, plus each holder added or re-committed); this
/// fixture does not. The bundle is asserted [`LATER_STEP_MS`] after prev.
///
/// # Panics
/// As [`ceremony_v2`].
#[must_use]
pub fn later_v2(
    prev: &TestCeremonyV2,
    holders: &[u8],
    serve_nodes: &[u8],
    signers: &[u8],
) -> TestCeremonyV2 {
    let spec = CeremonySpec {
        holders: holders.to_vec(),
        serve_nodes: serve_nodes.to_vec(),
        t0_ms: prev.spec.t0_ms,
        family_key_id: prev.spec.family_key_id.clone(),
    };
    check_spec(&spec);
    let held_holder = |h: u8| prev.holders.iter().find(|x| x.holder_seed == h).cloned();
    let placed: Vec<HolderV2> = holders
        .iter()
        .map(|h| held_holder(*h).unwrap_or_else(|| mint_holder(*h, spec.t0_ms)))
        .collect();
    let seats: Vec<SeatV2> = serve_nodes
        .iter()
        .map(|s| {
            prev.seats
                .iter()
                .find(|x| x.seed == *s)
                .cloned()
                .unwrap_or_else(|| mint_seat(*s, spec.t0_ms))
        })
        .collect();
    let voices: Vec<(CompositeSigningKey, String)> = signers
        .iter()
        .map(|s| {
            placed
                .iter()
                .find(|x| x.holder_seed == *s)
                .cloned()
                .or_else(|| held_holder(*s))
                .map_or_else(
                    || (test_key(*s), identity_ref_of(*s)),
                    |h| (test_key(h.seed), h.identity_ref),
                )
        })
        .collect();
    assemble_bundle(
        &spec,
        prev.version + 1,
        Some(prev.object_id),
        prev.asserted_at_ms + LATER_STEP_MS,
        placed,
        seats,
        Vec::new(),
        &voices,
        None,
    )
}

/// Mint a **recovery** over `prev` (CC 2.6.1.11, CC 4.2.6): a later bundle
/// with ONE statement, `iss` the holder `holder_seed`, signed by the
/// recovery key its commitment in force commits to, naming that key's
/// record. It changes that holder's seat alone: the holder is re-seated on a
/// new key with its own custody chain and commits a next recovery key, so
/// the spent commitment never returns. Every other holder, every seat and
/// the charter are as `prev` has them. The new records are asserted one
/// second before the bundle, which is asserted [`LATER_STEP_MS`] after prev.
///
/// A first recovery re-seats key `n + RECOVERED_SEED_OFFSET` and commits
/// `n + NEXT_RECOVERY_SEED_OFFSET`; a second re-seats
/// `n + SECOND_RECOVERED_SEED_OFFSET` and commits
/// `n + SECOND_NEXT_RECOVERY_SEED_OFFSET`.
///
/// # Panics
/// `holder_seed` is not a holder of `prev`, or was recovered twice already.
#[must_use]
pub fn recover_v2(prev: &TestCeremonyV2, holder_seed: u8) -> TestCeremonyV2 {
    let old = holder_of(prev, holder_seed);
    let (new_key, next) = if old.seed == holder_seed {
        (
            holder_seed + RECOVERED_SEED_OFFSET,
            holder_seed + NEXT_RECOVERY_SEED_OFFSET,
        )
    } else if old.seed == holder_seed + RECOVERED_SEED_OFFSET {
        (
            holder_seed + SECOND_RECOVERED_SEED_OFFSET,
            holder_seed + SECOND_NEXT_RECOVERY_SEED_OFFSET,
        )
    } else {
        panic!("recover_v2: holder {holder_seed} was recovered twice already")
    };
    recover_v2_with(prev, holder_seed, old.recovery_seed, new_key, next)
}

/// A recovery with every key chosen by the caller, for the witnesses of what
/// the reader must refuse: `recovery_signer_seed` signs the one statement
/// (its record is named), the holder is re-seated on `new_key_seed`, and
/// `next_recovery_seed` is committed. A `new_key_seed` must be one a custody
/// chain is carried for: `n + RECOVERED_SEED_OFFSET`,
/// `n + SECOND_RECOVERED_SEED_OFFSET`, or `n + RECOVERY_SEED_OFFSET` (the
/// first recovery key ITSELF: `recovery_key_is_signing_key`).
///
/// # Panics
/// `holder_seed` is not a holder of `prev`; a `new_key_seed` with no chain.
#[must_use]
pub fn recover_v2_with(
    prev: &TestCeremonyV2,
    holder_seed: u8,
    recovery_signer_seed: u8,
    new_key_seed: u8,
    next_recovery_seed: u8,
) -> TestCeremonyV2 {
    let i = prev
        .holders
        .iter()
        .position(|h| h.holder_seed == holder_seed)
        .unwrap_or_else(|| panic!("recover_v2: {holder_seed} is not a holder of prev"));
    let iref = prev.holders[i].identity_ref.clone();
    let at = prev.asserted_at_ms + LATER_STEP_MS;
    let rows_at = at - 1000;
    let rk = test_key(recovery_signer_seed);
    let chain = chain_for_key(holder_seed, new_key_seed);
    let record = holder_record(&iref, &test_key(new_key_seed), chain, rows_at);
    let rk_record = recovery_key_record(&iref, &rk, rows_at);
    let mut holders = prev.holders.clone();
    holders[i] = HolderV2 {
        seed: new_key_seed,
        holder_seed,
        recovery_seed: next_recovery_seed,
        kid: kid_of(new_key_seed),
        identity_ref: iref.clone(),
        record,
        recovery_commitment: recovery_commitment(&[test_key(next_recovery_seed)
            .public_key()
            .clone()]),
    };
    let signers = [(rk, iref.clone())];
    assemble_bundle(
        &prev.spec,
        prev.version + 1,
        Some(prev.object_id),
        at,
        holders,
        prev.seats.clone(),
        vec![rk_record],
        &signers,
        Some(iref),
    )
}

/// v62.0.0 (wave W1; CC 3.3.6.2, CC 5.3.4) — **a later bundle that
/// re-seats a seat on fresh X-Wing keys**: over `prev`, the seat
/// `seat_seed` gets a NEW binding (its bundle binding's payload with a fresh
/// `transit_xwing_pubkey` and `onion_hop_xwing_pubkey` of generation `gen`,
/// asserted one second before the bundle, signed by the seat's key); its key
/// record, every holder and every other seat are as `prev` has them.
/// `signers` are holder seeds, signing as in [`later_v2`]. The bundle is
/// asserted [`LATER_STEP_MS`] after prev.
///
/// # Panics
/// `seat_seed` is not a seat of `prev`.
#[must_use]
pub fn reseat_xwing_v2(
    prev: &TestCeremonyV2,
    seat_seed: u8,
    gen: u8,
    signers: &[u8],
) -> TestCeremonyV2 {
    let asserted_at = prev.asserted_at_ms + LATER_STEP_MS;
    let seats: Vec<SeatV2> = prev
        .seats
        .iter()
        .map(|seat| {
            if seat.seed != seat_seed {
                return seat.clone();
            }
            let transit = xwing_key(format!("transit-reseat-{gen}").as_bytes(), seat_seed);
            let onion = xwing_key(format!("onion-reseat-{gen}").as_bytes(), seat_seed);
            let (_, payload) = super::liveness::statement_parts(&seat.binding.statement)
                .expect("a fixture binding is a statement");
            let members: Vec<(Value, Value)> = payload
                .as_map()
                .expect("a fixture binding's payload is a map")
                .iter()
                .map(|(k, v)| {
                    let v = match k.as_text() {
                        Some("transit_xwing_pubkey") => Value::Bytes(transit.to_vec()),
                        Some("onion_hop_xwing_pubkey") => Value::Bytes(onion.to_vec()),
                        Some("asserted_at") => Value::Uint(asserted_at - 1_000),
                        _ => v.clone(),
                    };
                    (k.clone(), v)
                })
                .collect();
            let binding = sign_row(
                &test_key(seat.seed),
                &seat.identity_ref,
                BINDING_FAMILY,
                &Value::Map(members),
            );
            SeatV2 {
                binding,
                transit_xwing_pubkey: transit,
                onion_hop_xwing_pubkey: onion,
                ..seat.clone()
            }
        })
        .collect();
    assert!(
        seats
            .iter()
            .zip(&prev.seats)
            .any(|(a, b)| a.binding.row_id != b.binding.row_id),
        "reseat_xwing_v2: {seat_seed} is not a seat of prev"
    );
    let voices: Vec<(CompositeSigningKey, String)> = signers
        .iter()
        .map(|s| {
            let h = holder_of(prev, *s);
            (test_key(h.seed), h.identity_ref.clone())
        })
        .collect();
    assemble_bundle(
        &prev.spec,
        prev.version + 1,
        Some(prev.object_id),
        asserted_at,
        prev.holders.clone(),
        seats,
        Vec::new(),
        &voices,
        None,
    )
}

fn holder_of(prev: &TestCeremonyV2, holder_seed: u8) -> &HolderV2 {
    prev.holders
        .iter()
        .find(|h| h.holder_seed == holder_seed)
        .unwrap_or_else(|| panic!("{holder_seed} is not a holder of prev"))
}

/// The custody chain carried for holder `holder_seed`'s key `key_seed`.
fn chain_for_key(holder_seed: u8, key_seed: u8) -> Vec<Vec<u8>> {
    if key_seed == holder_seed {
        chain_of(HOLDER_CHAINS_HEX, holder_seed)
    } else if key_seed == holder_seed + RECOVERED_SEED_OFFSET {
        chain_of(RECOVERED_CHAINS_HEX, holder_seed)
    } else if key_seed == holder_seed + SECOND_RECOVERED_SEED_OFFSET {
        chain_of(SECOND_RECOVERED_CHAINS_HEX, holder_seed)
    } else if key_seed == holder_seed + RECOVERY_SEED_OFFSET {
        chain_of(RECOVERY_KEY_CHAINS_HEX, holder_seed)
    } else {
        panic!("no custody chain for key {key_seed} of holder {holder_seed}")
    }
}

/// Mint a later bundle over `prev` that changes ONE thing: holder
/// `holder_seed`'s recovery commitment, re-committed to
/// `test_key(recovery_seed)`. Every other party and the charter are as
/// `prev` has them; `signers` (holder seeds) sign with their current keys.
/// The reader counts it as any later bundle (a strict majority of prev's
/// holders, plus the re-committed holder), and concludes nothing for a
/// bundle naming a commitment the lineage has spent
/// (`recovery_commitment_spent`, CC 4.2.6: a spent commitment never
/// returns).
///
/// # Panics
/// `holder_seed` is not a holder of `prev`.
#[must_use]
pub fn recommit_v2(
    prev: &TestCeremonyV2,
    holder_seed: u8,
    recovery_seed: u8,
    signers: &[u8],
) -> TestCeremonyV2 {
    let i = prev
        .holders
        .iter()
        .position(|h| h.holder_seed == holder_seed)
        .unwrap_or_else(|| panic!("recommit_v2: {holder_seed} is not a holder of prev"));
    let mut holders = prev.holders.clone();
    holders[i].recovery_seed = recovery_seed;
    holders[i].recovery_commitment =
        recovery_commitment(&[test_key(recovery_seed).public_key().clone()]);
    let voices: Vec<(CompositeSigningKey, String)> = signers
        .iter()
        .map(|s| {
            holders.iter().find(|h| h.holder_seed == *s).map_or_else(
                || (test_key(*s), identity_ref_of(*s)),
                |h| (test_key(h.seed), h.identity_ref.clone()),
            )
        })
        .collect();
    assemble_bundle(
        &prev.spec,
        prev.version + 1,
        Some(prev.object_id),
        prev.asserted_at_ms + LATER_STEP_MS,
        holders,
        prev.seats.clone(),
        Vec::new(),
        &voices,
        None,
    )
}

/// The standard ceremony ([`CeremonySpec::standard`]), minted once per
/// process.
#[must_use]
pub fn bundle_v2() -> &'static TestCeremonyV2 {
    static STANDARD: OnceLock<TestCeremonyV2> = OnceLock::new();
    STANDARD.get_or_init(|| ceremony_v2(&CeremonySpec::standard()))
}

/// What an install placed.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct InstalledV2 {
    /// The bundle's object id.
    pub object_id: Digest32,
    /// Its version.
    pub version: u64,
}

/// Install `c` on `dir` through the real import door
/// (`edition2::genesis::put_genesis_bundle`): one statement list, the named
/// rows in put order then the voices, under [`TestCeremonyV2::anchor`],
/// after registering the MOCK attestation root with the door's custody
/// gate (`edition2::genesis::add_test_attestation_root`).
///
/// Idempotent: the outcome is read back from the held state, so a bundle
/// already held is Ok whatever the door says of a second offer.
///
/// Under `test-anchor` outside `cfg(test)` the door trusts the MOCK root
/// only while `ciris_verify_core::test_anchor::test_anchor_active()`.
///
/// # Errors
/// The door's refusal, unchanged, when the bundle is not held after it.
pub async fn install_ceremony_v2<F>(dir: &F, c: &TestCeremonyV2) -> Result<InstalledV2, Error>
where
    F: FederationDirectory + ?Sized,
{
    super::genesis::add_test_attestation_root(mock_attestation_root_der());
    let mut statements: Vec<Vec<u8>> = c
        .rows_in_put_order()
        .into_iter()
        .map(|r| r.statement.clone())
        .collect();
    statements.extend(c.voices.iter().cloned());
    let anchor = c.anchor();
    let offered = super::genesis::put_genesis_bundle(dir, &statements, Some(&anchor)).await;
    let held = super::genesis::genesis_in_force(dir).await?;
    if held.valid.iter().any(|p| p.object_id == c.object_id) {
        return Ok(InstalledV2 {
            object_id: c.object_id,
            version: c.version,
        });
    }
    match offered {
        Err(e) => Err(e),
        // v62.0.0 (wave GC5) — a bundle the door HELD (kept, concluding
        // nothing: its count unmet, a named row Invalid, ...) is not
        // installed: the fixture answers its held reason as the error.
        Ok(admission) => Err(Error::malformed_row(
            super::door::PLANE,
            admission
                .not_placed
                .iter()
                .find(|n| n.object_id == c.object_id)
                .map_or(
                    crate::federation::malformed_row::GENESIS_BUNDLE_MALFORMED,
                    |n| n.token,
                ),
            format!(
                "test_ceremony_v2: bundle {} is not held after the door: {:?}",
                hex::encode(c.object_id),
                admission.not_placed
            ),
        )),
    }
}

/// [`install_ceremony_v2`] of [`bundle_v2`]. Replaces the earlier seeds:
/// `seed_genesis_accord_holders` + `seed_family_and_canonical`,
/// `seed_accord_family`, `seed_canonical_servers`, `seed_delegation_plane`,
/// `seed_canonical_community_from` and `install_test_ceremony_outputs*`.
///
/// # Errors
/// As [`install_ceremony_v2`].
pub async fn install_v2<F>(dir: &F) -> Result<InstalledV2, Error>
where
    F: FederationDirectory + ?Sized,
{
    install_ceremony_v2(dir, bundle_v2()).await
}

/// [`install_v2`] on an Engine's directory.
///
/// # Errors
/// As [`install_ceremony_v2`].
#[cfg(any(feature = "sqlite", feature = "postgres"))]
pub async fn install_v2_engine(engine: &crate::Engine) -> Result<InstalledV2, Error> {
    let dir = engine.federation_directory();
    install_v2(dir.as_ref()).await
}
