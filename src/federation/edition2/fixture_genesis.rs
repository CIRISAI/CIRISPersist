//! v62.0.0 (JSON-cut slice C) — **`test_ceremony_v2`**: a signed
//! `ceg-genesis-bundle/2` for tests, and the helpers that install it through
//! the real doors (CC 2.6.1.11, CC 4.2.2.1, CC 5.3.4).
//!
//! A v62 node boots pre-genesis: nothing is baked, and nothing is rooted
//! until a bundle/2 arrives at the import door. A test that needs a root
//! mints one here, in four steps:
//!
//! 1. the holders' and serve seats' composite keys come from fixed seeds
//!    ([`test_key`]: ML-DSA-65 seed `[n; 32]`, Ed25519 seed `[n + 100; 32]`,
//!    Verify's vector rule and the door fixtures' `key(n)`);
//! 2. each holder's `key:record` carries the custody evidence the reader's
//!    gate verifies (`YubiKey_5_FIPS`, `removable_offline`, a chain to
//!    Verify's MOCK attestation root, [`attestation_roots`]); each seat has a
//!    `node` record ending one year out and an `identity:occurrence` binding
//!    carrying its transport destination and its two X-Wing keys;
//! 3. one bundle payload names those rows by row id in `refs.also.cites`,
//!    with `holders`, `serve_nodes` and the charter (one recovery
//!    commitment per holder, scope `infra:attest` + `infra:serve`);
//! 4. every holder signs it.
//!
//! [`install_ceremony_v2`] offers the named rows and the voices to the
//! bundle/2 import door, the door a production node uses. Nothing here
//! places a row by its own rules: Verify's reader does.
//!
//! The custody chains are generated by
//! `scripts/gen_test_ceremony_v2_custody.py`, which reproduces Verify
//! v23.3.0's vector PKI and checks its bytes against Verify's pool
//! (`fixture_genesis_custody`). The root says MOCK in its name and is
//! trusted only by a reader handed it.
//!
//! Gated `cfg(any(test, feature = "test-anchor"))`: no production build
//! contains it.

