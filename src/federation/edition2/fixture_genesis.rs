/// Holder seeds of the standard ceremony (Verify's vector keys A, B, C).
pub const HOLDER_SEEDS: [u8; 3] = [1, 2, 3];

/// Serve-node (seat) seeds of the standard ceremony (Verify's S1, S2).
pub const SERVE_NODE_SEEDS: [u8; 2] = [11, 12];

/// The holder seeds a custody chain exists for. A spec's holders must be
/// among these.
pub const HOLDER_SEED_RANGE: core::ops::RangeInclusive<u8> = 1..=7;

/// The recovery-key seed offset (Verify's `REC` rule: holder `n`'s recovery
/// key is key `n + 50`).
pub const RECOVERY_SEED_OFFSET: u8 = 50;

/// The seed offset of a holder's NEXT recovery key, committed by
/// [`recover_v2`] (Verify's `A_REC2 = 61` for holder 1).
pub const NEXT_RECOVERY_SEED_OFFSET: u8 = 60;

/// The signing-key seed offset after a recovery: [`recover_v2`] re-seats
/// holder `n` on key `n + 40` (Verify's `A_NEW = 41` for holder 1).
pub const RECOVERED_SEED_OFFSET: u8 = RECOVERED_KEY_OFFSET;

/// After a SECOND recovery holder `n` signs with key `n + 80`, and commits
/// recovery key `n + 70` next.
pub const SECOND_RECOVERED_SEED_OFFSET: u8 = SECOND_RECOVERED_KEY_OFFSET;

/// The recovery key a second recovery commits next: `n + 70`.
pub const SECOND_NEXT_RECOVERY_SEED_OFFSET: u8 = 70;

/// `family_key_id` of the standard ceremony.
pub const FAMILY_KEY_ID: &str = "humanity-accord";

/// One day in milliseconds.
pub const DAY_MS: u64 = 86_400_000;

/// 365 days in milliseconds: the longest a `node` record may run (CC
/// 2.4.1.1).
pub const YEAR_MS: u64 = 31_536_000_000;

/// The gap between a later bundle and its predecessor.
pub const LATER_STEP_MS: u64 = 60_000;

const ROW_TYPE: &str = "scores";
const HARDWARE_CLASS: &str = "YubiKey_5_FIPS";
const PQ_CUSTODY: &str = "removable_offline";
const APP_NAME: &str = "ciris.federation";
const ASPECT: &str = "serve";

/// Composite test key `seed`: ML-DSA-65 seed `[seed; 32]`, Ed25519 seed
/// `[seed + 100; 32]`.
#[must_use]
pub fn test_key(seed: u8) -> CompositeSigningKey {
    CompositeSigningKey::from_seeds(&[seed; 32], &[seed.wrapping_add(100); 32])
}

/// A holder's recovery key: [`test_key`]`(seed + 50)`.
#[must_use]
pub fn recovery_key(holder_seed: u8) -> CompositeSigningKey {
    test_key(holder_seed.wrapping_add(RECOVERY_SEED_OFFSET))
}

/// The kid of [`test_key`]`(seed)`.
#[must_use]
pub fn kid_of(seed: u8) -> Digest32 {
    thumbprint(test_key(seed).public_key())
}

/// The identity reference of [`test_key`]`(seed)`.
#[must_use]
pub fn identity_ref_of(seed: u8) -> String {
    identity_ref(&kid_of(seed))
}

/// What a ceremony seats, and when.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CeremonySpec {
    /// Holder seeds, each in [`HOLDER_SEED_RANGE`].
    pub holders: Vec<u8>,
    /// Seat seeds, disjoint from the holders and their recovery keys.
    pub serve_nodes: Vec<u8>,
    /// The records' instant (POSIX ms). A fresh bundle is asserted at
    /// `t0_ms + DAY_MS / 2`; seat records end at `t0_ms + YEAR_MS`.
    pub t0_ms: u64,
    /// The bundle's `family_key_id`.
    pub family_key_id: String,
}

impl CeremonySpec {
    /// [`HOLDER_SEEDS`], [`SERVE_NODE_SEEDS`], [`FAMILY_KEY_ID`], with `t0`
    /// at yesterday's UTC midnight, so the bundle (yesterday noon) is in the
    /// past and every seat record is live for the next 364 days. The bytes
    /// move with the date; a test that pins bytes uses [`Self::at`].
    #[must_use]
    pub fn standard() -> Self {
        let now = u64::try_from(chrono::Utc::now().timestamp_millis()).unwrap_or(0);
        Self::at((now / DAY_MS) * DAY_MS - DAY_MS)
    }

    /// The standard sets with a fixed `t0` (deterministic bytes).
    #[must_use]
    pub fn at(t0_ms: u64) -> Self {
        CeremonySpec {
            holders: HOLDER_SEEDS.to_vec(),
            serve_nodes: SERVE_NODE_SEEDS.to_vec(),
            t0_ms,
            family_key_id: FAMILY_KEY_ID.to_owned(),
        }
    }
}

/// A named row: its statement and the row id the bundle cites.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NamedRow {
    /// The node-computed row id.
    pub row_id: Digest32,
    /// The `COSE_Sign1` row statement.
    pub statement: Vec<u8>,
}

impl NamedRow {
    fn of(statement: Vec<u8>) -> Self {
        let row_id = RowId::of_statement(&statement)
            .expect("a fixture row statement carries a row id")
            .0;
        NamedRow { row_id, statement }
    }
}

/// A seated holder.
#[derive(Clone, Debug)]
pub struct HolderV2 {
    /// The seed of the key it signs with now ([`HolderV2::holder_seed`]
    /// until a recovery, then `holder_seed + RECOVERED_SEED_OFFSET`).
    pub seed: u8,
    /// The seed whose key names the holder: its identity reference is
    /// [`identity_ref_of`]`(holder_seed)` for good (CC 2.6.1.7).
    pub holder_seed: u8,
    /// The seed of the recovery key its commitment commits to.
    pub recovery_seed: u8,
    /// The kid of the key it signs with now.
    pub kid: Digest32,
    /// Its identity reference.
    pub identity_ref: String,
    /// Its current `key:record` (`accord_holder`, with custody evidence).
    pub record: NamedRow,
    /// The commitment over `test_key(recovery_seed)`.
    pub recovery_commitment: Digest32,
}

/// A seated serve node.
#[derive(Clone, Debug)]
pub struct SeatV2 {
    /// Its key seed.
    pub seed: u8,
    /// Its kid.
    pub kid: Digest32,
    /// Its identity reference.
    pub identity_ref: String,
    /// Its `key:record` (`node`, ending `t0 + YEAR_MS`).
    pub record: NamedRow,
    /// Its `identity:occurrence` binding, citing the record.
    pub binding: NamedRow,
    /// The binding's transit X-Wing key.
    pub transit_xwing_pubkey: [u8; XWING_PUBKEY_LEN],
    /// The binding's onion-hop X-Wing key.
    pub onion_hop_xwing_pubkey: [u8; XWING_PUBKEY_LEN],
}

/// A minted bundle and every row it names.
#[derive(Clone, Debug)]
pub struct TestCeremonyV2 {
    /// What was minted.
    pub spec: CeremonySpec,
    /// `version`: 1 for [`ceremony_v2`], prev's + 1 for [`later_v2`].
    pub version: u64,
    /// `refs.prev`, for a later bundle.
    pub prev: Option<Digest32>,
    /// The bundle's `asserted_at` (POSIX ms).
    pub asserted_at_ms: u64,
    /// The holders, in spec order.
    pub holders: Vec<HolderV2>,
    /// The seats, in spec order.
    pub seats: Vec<SeatV2>,
    /// Further rows the bundle names: a recovery's recovery-key record.
    pub extra_rows: Vec<NamedRow>,
    /// The holder a recovery bundle recovers (its identity reference).
    pub recovered: Option<String>,
    /// The bundle payload.
    pub payload: Value,
    /// One `ceg-genesis-bundle/2` statement per signer.
    pub voices: Vec<Vec<u8>>,
    /// The bundle's object id (`["CEG-object/2", typ, null, payload]`).
    pub object_id: Digest32,
}

impl TestCeremonyV2 {
    /// Every named row, by row id (the shape of Verify's
    /// `GenesisInput.rows`).
    #[must_use]
    pub fn rows(&self) -> BTreeMap<Digest32, Vec<u8>> {
        self.rows_in_put_order()
            .into_iter()
            .map(|r| (r.row_id, r.statement.clone()))
            .collect()
    }

    /// The named rows in the order a node can admit them: holder records,
    /// seat records, then the bindings (each signed by a key whose record
    /// precedes it).
    #[must_use]
    pub fn rows_in_put_order(&self) -> Vec<&NamedRow> {
        self.holders
            .iter()
            .map(|h| &h.record)
            .chain(self.extra_rows.iter())
            .chain(self.seats.iter().map(|s| &s.record))
            .chain(self.seats.iter().map(|s| &s.binding))
            .collect()
    }

    /// The reader's anchor for this bundle: its holders' thumbprints (CC
    /// 5.3.4).
    #[must_use]
    pub fn anchor(&self) -> Anchor {
        Anchor::Thumbprints(self.holder_kids())
    }

    /// The holders' kids.
    #[must_use]
    pub fn holder_kids(&self) -> BTreeSet<Digest32> {
        self.holders.iter().map(|h| h.kid).collect()
    }

    /// The holders' identity references, in spec order.
    #[must_use]
    pub fn holder_identity_refs(&self) -> Vec<String> {
        self.holders
            .iter()
            .map(|h| h.identity_ref.clone())
            .collect()
    }

    /// The seats' identity references, in spec order.
    #[must_use]
    pub fn serve_node_identity_refs(&self) -> Vec<String> {
        self.seats.iter().map(|s| s.identity_ref.clone()).collect()
    }

    /// Seat `i`'s identity reference. Replaces
    /// `canonical_genesis_bundle().serve_nodes[i].record.key_id`.
    #[must_use]
    pub fn serve_node_identity_ref(&self, i: usize) -> &str {
        &self.seats[i].identity_ref
    }

    /// Holder `i`'s identity reference. Replaces
    /// `canonical_genesis_bundle().holders[i].record.key_id`.
    #[must_use]
    pub fn holder_identity_ref(&self, i: usize) -> &str {
        &self.holders[i].identity_ref
    }

    /// Holder `i`'s signing key.
    #[must_use]
    pub fn holder_key(&self, i: usize) -> CompositeSigningKey {
        test_key(self.holders[i].seed)
    }

    /// Holder `i`'s committed recovery key.
    #[must_use]
    pub fn holder_recovery_key(&self, i: usize) -> CompositeSigningKey {
        test_key(self.holders[i].recovery_seed)
    }

    /// Seat `i`'s signing key.
    #[must_use]
    pub fn serve_node_key(&self, i: usize) -> CompositeSigningKey {
        test_key(self.seats[i].seed)
    }
}

