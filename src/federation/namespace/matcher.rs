    fn provenance_locale_is_canonical_bcp47() {
        let dim = |tag: &str| format!("provenance:build_manifest:agent-3.2.1:locale:{tag}:v1");
        let family = Some("provenance:build_manifest:{target}:locale:{lang_code}");
        for ok in [
            "en-US",
            "en",
            "zh-Hans-CN",
            "es-419",
            "de-CH-1996",
            "x-private",
            "i-default",
        ] {
            let m = match_family(&dim(ok));
            assert_eq!((m.family, m.refusal), (family, None), "{ok}");
        }
        // Admitted by the pre-release pattern, refused now: non-canonical
        // casing and extlang forms (written as their preferred value).
        for bad in ["en-us", "EN", "zh-hans-cn", "zh-cmn-Hans-CN", "sgn-BE-FR"] {
            let m = match_family(&dim(bad));
            assert_eq!(
                (m.family, m.refusal),
                (family, Some(Refusal::CaseMalformed)),
                "{bad}"
            );
        }
    }

    #[test]
    fn version_segment_parser_reads_the_manifest_pattern() {
        for ok in ["v1", "v2", "v10", "v1.2", "v1.2.3"] {
            assert!(is_version_segment(ok), "{ok}");
        }
        for bad in ["V1", "v", "v1.", "1", "v1a", "vv1", "v1:v2", ""] {
            assert!(!is_version_segment(bad), "{bad}");
        }
        assert_eq!(trailing_version("objection:raised:v1"), Some("v1"));
        assert_eq!(trailing_version("benchmark:he300:x:v1.2"), Some("v1.2"));
        assert_eq!(trailing_version("foo:v1:bar"), None, "trailing only");
        assert_eq!(trailing_version("v1"), None, "a lone segment is no tail");
        assert!(is_version_exempt("attestation:self_verify"));
        assert!(is_version_exempt(
            "identity:canonical_binding:{canonical_hash}"
        ));
        assert!(!is_version_exempt("config:{scope}"));
    }
