/// **The one version parser** (v50.0.0, CIRISPersist#924) — does `segment`
/// match `_meta.case_rule.version_segment.pattern` (`^v[0-9]+(\.[0-9]+)*$` on
/// rc5)?
///
/// Replaces the three persist carried: `admission::contains_version_segment`
/// (a `:v[0-9]+` byte scan ANYWHERE in the dimension), `schema_resolver::
/// is_version_segment` (`^v[0-9]+$`, no dotted versions) and the ledger gate's
/// `strip_prefix('v')`.
#[must_use]
pub fn is_version_segment(segment: &str) -> bool {
    rules().version.is_match(segment)
}

/// Does `token` match `_meta.case_rule.vocab_pattern` (a lowercase CC
/// vocabulary token)? For hand checks the registry cannot express as a row.
#[must_use]
pub fn is_vocab_token(token: &str) -> bool {
    rules().vocab.is_match(token)
}

/// The trailing version segment of `dimension` — its LAST `:`-segment, when
/// that matches the manifest's pattern. CC 3.1.7 R3: the version is trailing,
/// exactly one, after the family's own segments.
#[must_use]
pub fn trailing_version(dimension: &str) -> Option<&str> {
    dimension
        .rsplit(':')
        .next()
        .filter(|last| dimension.contains(':') && is_version_segment(last))
}

/// Is `family` (a registry prefix) in `_meta.case_rule.version_segment.exempt`
/// — the families that carry no version tail (the five mechanism-named
/// attestation-ladder families and `identity:canonical_binding:{canonical_hash}`)?
///
/// The two carve-outs persist used to spell in code
/// (`is_attestation_ladder_dimension`, `parse_canonical_binding_hash`) are this
/// list; they stopped being code in v50.0.0.
#[must_use]
pub fn is_version_exempt(family: &str) -> bool {
    rules().exempt.iter().any(|e| e == family)
}

/// Whether the manifest REQUIRES the version segment
/// (`_meta.case_rule.version_segment.required`).
#[must_use]
pub fn version_segment_required() -> bool {
    rules().version_required
}

/// The `_meta.case_rule.reserved_stems` stems, in manifest order.
pub fn reserved_stems() -> impl Iterator<Item = &'static str> {
    rules().reserved_stems.iter().map(String::as_str)
}

/// The `(rule, cc_ref)` of the longest `_meta.case_rule.reserved_stems` stem
/// of `kind: reserved` that `dimension` sits under, if any. (A `kind: gated`
/// stem — `age_self_declared:` — states an emitter rule without a
/// reservation, so it is not a reserved rule; the matcher still refuses its
/// unclaimed leaves.) What a classifier reports for a dimension
/// under a reserved stem that no row claims — the reservation covers the
/// leaves nobody minted yet (CC 3.1.7 R3), so it must not read as open.
#[must_use]
pub fn reserved_stem_rule(dimension: &str) -> Option<(&'static str, &'static str)> {
    rules()
        .reserved_stem_rules
        .iter()
        .filter(|(stem, _, _)| dimension.starts_with(stem.as_str()))
        .max_by_key(|(stem, _, _)| stem.len())
        .map(|(_, rule, cc_ref)| (rule.as_str(), cc_ref.as_str()))
}

/// A family's `{placeholder}` values, when its row enumerates them
/// (`segments[].values`), with whether the enumeration is OPEN.
#[must_use]
pub fn placeholder_values(family: &str, placeholder: &str) -> Option<(&'static [String], bool)> {
    let fam = rules().family(family)?;
    let seg = fam.segments.iter().find(|s| s.segment == placeholder)?;
    seg.values.as_deref().map(|v| (v, seg.open))
}

/// A wildcard family's published `leaves`, and whether they are closed.
#[must_use]
pub fn family_leaves(family: &str) -> Option<(&'static [String], bool)> {
    let fam = rules().family(family)?;
    Some((fam.leaves.as_slice(), fam.leaves_closed))
}

/// A class-conformant sample dimension for `family` — a port of the
/// reference's `instantiate(fam, with_version=True)`, the same sample CC's
/// generator round-trips every family through. For tests that need "an
/// ordinary dimension on this family" (a literal stem such as `"system:"` is
/// not one: it has an empty segment and is malformed).
#[cfg(test)]
#[must_use]
pub(crate) fn sample_dimension(family: &str) -> Option<String> {
    let fam = rules().family(family)?;
    let mut out: Vec<String> = Vec::new();
    for seg in &fam.segments {
        let tok = match seg.class {
            Class::Literal => seg.segment.clone(),
            Class::Wildcard => "leaf".to_owned(),
            Class::Vocab => {
                let t = match &seg.values {
                    Some(v) if !v.is_empty() => v[0].clone(),
                    _ if seg.segment == "{version}" => "v1".to_owned(),
                    _ => "sample".to_owned(),
                };
                if seg.multi {
                    format!("{t}:sub")
                } else {
                    t
                }
            }
            Class::External => match seg.name.as_str() {
                "lang_code" => "en-US".to_owned(),
                "rating" => "PG-13".to_owned(),
                _ => "USD".to_owned(),
            },
            Class::Value | Class::Hex => match seg.pattern.as_ref().map(Regex::as_str) {
                Some(p) if p.contains("0-9") && !p.contains("a-f") => "42".to_owned(),
                Some(p) if p.contains("{64}") => "abcdef0123456789".repeat(4),
                _ if seg.class == Class::Hex => "ab12".to_owned(),
                _ if seg.multi => "id1:id2".to_owned(),
                _ => "id1".to_owned(),
            },
        };
        out.push(tok);
    }
    if !fam.ends_version() {
        out.push("v1".to_owned());
    }
    Some(out.join(":"))
}

/// Is `prefix` (ending in `:`) a run of LITERAL segments that some registry
/// family starts with, byte for byte — `"detection:distributive:access:"` for
/// `detection:distributive:access:{resource_type}`, `"system:"` for
/// `system:*`? The spelling check a hand-written reserved-rule prefix must
/// pass (`reserved_prefix_rules_match_manifest_leaves`).
#[must_use]
pub fn is_literal_family_prefix(prefix: &str) -> bool {
    let Some(body) = prefix.strip_suffix(':') else {
        return false;
    };
    let want: Vec<&str> = body.split(':').collect();
    rules().families.iter().any(|f| {
        f.segments.len() > want.len()
            && f.segments
                .iter()
                .zip(&want)
                .all(|(s, w)| s.class == Class::Literal && s.segment == *w)
    })
}

