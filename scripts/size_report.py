#!/usr/bin/env python3
"""size_report.py — per-file size of src/, recorded in evidence/size.tsv
(CIRISPersist#934, #1076 slice T).

    scripts/size_report.py write                 regenerate evidence/size.tsv
    scripts/size_report.py print                 the generated text on stdout
    scripts/size_report.py check [--against REF] [--fail-if-backends-grew]
                                                 per-file delta, working tree vs baseline

One row per `src/**/*.rs` file: code, comment and blank lines (tokei's three
columns, counted here with the stdlib so no tool has to be installed), plus a
`BACKENDS` row (src/store/{sqlite,postgres}.rs summed) and a `TOTAL` row.
Rows are sorted by path; the file carries no version and no date, so it only
changes when src/ does.

The count is comment-aware (`//`, nested `/* */`, doc comments) and string-aware
(a `/*` or `//` inside a string literal, raw strings included, is code). It is
`#[cfg(test)]`-BLIND on purpose: this is a size measure, not a test stripper —
inline test modules are lines a reader has to page past too.

CHECK. The baseline is the committed evidence/size.tsv, or, with `--against
REF`, src/ as it is at that git ref (measured from `git show`, so a stale tsv
cannot mislead it). It prints every file whose total moved, the BACKENDS and
TOTAL deltas, and exits 0: a REPORT. Only `--fail-if-backends-grew` turns it
into a gate (exit 1 when the BACKENDS total grew). That flag is #934 step 1's
acceptance criterion — "the net line count of the three backend files goes
DOWN" — and is not on main's gates: nothing new goes red without the operator.

EXIT CODES: 0 report printed (or written); 1 backends grew under
`--fail-if-backends-grew`; 2 usage, or no baseline to compare against.
"""
from __future__ import annotations

import argparse
import os
import subprocess
import sys
from pathlib import Path

TARGET = "evidence/size.tsv"
BACKENDS = ("src/store/sqlite.rs", "src/store/postgres.rs")

HEADER = """\
# evidence/size.tsv — per-file line counts of src/**/*.rs (CIRISPersist#934).
# GENERATED by `scripts/size_report.py write`; `check` diffs the working tree
# against it (or `--against <ref>`). Comment-aware, #[cfg(test)]-blind.
# BACKENDS = src/store/{sqlite,postgres}.rs summed; TOTAL = every row.
path\tcode\tcomment\tblank\tlines
"""


def root() -> Path:
    return Path(os.environ.get("SIZE_REPORT_ROOT") or Path(__file__).resolve().parent.parent)


# ── the counter ──────────────────────────────────────────────────────────
def count_rust(text: str) -> tuple[int, int, int]:
    """(code, comment, blank) for one Rust source text.

    A line is BLANK if it is whitespace only (outside a string), COMMENT if it
    holds comment text and no code, CODE otherwise. A line inside a multi-line
    string literal is code."""
    code = comment = blank = 0
    depth = 0           # nested /* */ depth carried across lines
    in_str = False      # inside a "..." (or b"...") literal
    raw_hashes = -1     # inside r#"..."#: the number of hashes; -1 = not in one
    for line in text.splitlines():
        has_code = has_comment = False
        if in_str or raw_hashes >= 0:
            has_code = True     # a continuation line of a string literal
        i, n = 0, len(line)
        while i < n:
            c = line[i]
            if depth:
                has_comment = True
                if line.startswith("/*", i):
                    depth += 1; i += 2
                elif line.startswith("*/", i):
                    depth -= 1; i += 2
                else:
                    i += 1
                continue
            if in_str:
                if c == "\\":
                    i += 2
                elif c == '"':
                    in_str = False; i += 1
                else:
                    i += 1
                continue
            if raw_hashes >= 0:
                close = '"' + "#" * raw_hashes
                if line.startswith(close, i):
                    i += len(close); raw_hashes = -1
                else:
                    i += 1
                continue
            if c.isspace():
                i += 1
                continue
            if line.startswith("//", i):
                has_comment = True
                break
            if line.startswith("/*", i):
                has_comment = True; depth = 1; i += 2
                continue
            has_code = True
            if c == '"':
                in_str = True; i += 1
            elif c in "rb" and _raw_start(line, i) is not None:
                hashes, j = _raw_start(line, i)
                raw_hashes = hashes; i = j
            elif c == "b" and line.startswith('b"', i):
                in_str = True; i += 2
            elif c == "'":
                i = _skip_char_or_lifetime(line, i)
            elif c.isalnum() or c == "_":
                # an identifier: skip it whole, so the `r`/`b` of `for`/`sub`
                # is never read as a raw-string prefix
                while i < n and (line[i].isalnum() or line[i] == "_"):
                    i += 1
            else:
                i += 1
        if has_code:
            code += 1
        elif has_comment:
            comment += 1
        else:
            blank += 1
    return code, comment, blank


def _raw_start(line: str, i: int):
    """If a raw string (r"…", r#"…"#, br#"…"#) starts at i: (hashes, index after the quote)."""
    j = i
    if line.startswith("br", j):
        j += 2
    elif line[j] == "r":
        j += 1
    else:
        return None
    k = j
    while k < len(line) and line[k] == "#":
        k += 1
    if k < len(line) and line[k] == '"':
        return k - j, k + 1
    return None


def _skip_char_or_lifetime(line: str, i: int) -> int:
    """At a `'`: skip a char literal ('x', '\\n', '\\u{..}', '"') or a lifetime ('a)."""
    if line.startswith("'\\", i):
        end = line.find("'", i + 2)
        return end + 1 if end != -1 else len(line)
    if i + 2 < len(line) and line[i + 2] == "'":
        return i + 3
    return i + 1   # a lifetime or label: the identifier is skipped by the caller's loop


# ── the table ────────────────────────────────────────────────────────────
Row = tuple[int, int, int]


def measure_tree(base: Path) -> dict[str, Row]:
    rows: dict[str, Row] = {}
    for p in sorted((base / "src").rglob("*.rs")):
        rel = p.relative_to(base).as_posix()
        rows[rel] = count_rust(p.read_text(encoding="utf-8", errors="replace"))
    return rows


def measure_ref(base: Path, ref: str) -> dict[str, Row]:
    def git(*args: str) -> bytes:
        return subprocess.run(["git", "-C", str(base), *args], check=True,
                              capture_output=True).stdout
    try:
        names = git("ls-tree", "-r", "--name-only", ref, "--", "src").decode().split("\n")
    except subprocess.CalledProcessError as e:
        raise SystemExit(f"size_report: cannot list src/ at {ref!r}: "
                         f"{e.stderr.decode(errors='replace').strip()}") from None
    rows: dict[str, Row] = {}
    for rel in sorted(n for n in names if n.endswith(".rs")):
        rows[rel] = count_rust(git("show", f"{ref}:{rel}").decode("utf-8", errors="replace"))
    return rows


def _sum(rows, keys) -> Row:
    picked = [rows[k] for k in keys if k in rows]
    return tuple(sum(r[i] for r in picked) for i in range(3))  # type: ignore[return-value]


def render(rows: dict[str, Row]) -> str:
    out = [HEADER]
    for path in sorted(rows):
        c, m, b = rows[path]
        out.append(f"{path}\t{c}\t{m}\t{b}\t{c + m + b}\n")
    for label, (c, m, b) in (("BACKENDS", _sum(rows, BACKENDS)), ("TOTAL", _sum(rows, rows))):
        out.append(f"{label}\t{c}\t{m}\t{b}\t{c + m + b}\n")
    return "".join(out)


def parse(text: str) -> dict[str, Row]:
    rows: dict[str, Row] = {}
    for line in text.splitlines():
        if not line or line.startswith("#") or line.startswith("path\t"):
            continue
        f = line.split("\t")
        if len(f) != 5 or f[0] in ("BACKENDS", "TOTAL"):
            continue
        rows[f[0]] = (int(f[1]), int(f[2]), int(f[3]))
    return rows


# ── check ────────────────────────────────────────────────────────────────
def report(old: dict[str, Row], new: dict[str, Row], label: str) -> int:
    """Print the delta; return the BACKENDS total delta."""
    def tot(r: Row | None) -> int:
        return sum(r) if r else 0

    print(f"size: working tree vs {label}")
    moved = []
    for path in sorted(set(old) | set(new)):
        o, n = old.get(path), new.get(path)
        if tot(o) != tot(n) or (o is None) != (n is None):
            tag = "added" if o is None else "removed" if n is None else ""
            moved.append((path, tot(o), tot(n), tag))
    if moved:
        print(f"  {'file':<60} {'before':>8} {'after':>8} {'delta':>8}")
        for path, o, n, tag in moved:
            print(f"  {path:<60} {o:>8} {n:>8} {n - o:>+8} {tag}".rstrip())
    else:
        print("  no file changed size")
    deltas = {}
    for name, keys in (("BACKENDS", BACKENDS), ("TOTAL", None)):
        o = sum(_sum(old, keys or old)); n = sum(_sum(new, keys or new))
        deltas[name] = n - o
        print(f"  {name:<60} {o:>8} {n:>8} {n - o:>+8}")
    return deltas["BACKENDS"]


def main(argv: list[str]) -> int:
    # A Windows runner's stdout is cp1252: a non-ASCII path would kill the
    # report mid-table (the v54.1.0 ci_cache_trim lesson).
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8", errors="replace")
    ap = argparse.ArgumentParser(prog="size_report.py", description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("write")
    sub.add_parser("print")
    ck = sub.add_parser("check")
    ck.add_argument("--against", metavar="REF",
                    help="baseline = src/ at this git ref (default: the committed tsv)")
    ck.add_argument("--fail-if-backends-grew", action="store_true",
                    help="exit 1 if src/store/{sqlite,postgres}.rs grew in total")
    args = ap.parse_args(argv[1:])

    base = root()
    if args.cmd == "print":
        sys.stdout.write(render(measure_tree(base)))
        return 0
    if args.cmd == "write":
        (base / TARGET).write_text(render(measure_tree(base)), encoding="utf-8", newline="\n")
        print(f"wrote {TARGET}")
        return 0

    if args.against:
        old, label = measure_ref(base, args.against), args.against
    else:
        tsv = base / TARGET
        if not tsv.is_file():
            print(f"size_report: no {TARGET} to compare against "
                  f"(run `scripts/size_report.py write`, or pass --against REF)", file=sys.stderr)
            return 2
        old, label = parse(tsv.read_text(encoding="utf-8")), f"committed {TARGET}"
    grew = report(old, measure_tree(base), label)
    if args.fail_if_backends_grew and grew > 0:
        print(f"RED: the three backend files grew by {grew} lines "
              f"(#934: each door moved onto the shared side must shrink them)")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
