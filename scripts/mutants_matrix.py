#!/usr/bin/env python3
"""mutants_matrix.py — scope files in, detection matrix out (CIRISPersist#1024).

`scripts/mutants.sh` drives a mutation tool; this script does the two parts
that are not shell: it resolves a scope file into the tool's own filter
arguments, and it turns the tool's raw output into ONE matrix format,
whichever tool produced it.

    mutants_matrix.py tests <scope>                     the scope's nextest filterset
    mutants_matrix.py resolve cargo-mutants <scope> <diff-out>
                                                        cargo-mutants args, one per line;
                                                        writes the scope as a diff to <diff-out>
    mutants_matrix.py resolve mutest <scope>            mutest's --filter-mutations value
    mutants_matrix.py collect cargo-mutants <mutants.out> <scope> <out-dir> [k=v ...]
    mutants_matrix.py collect mutest <json-dir> <scope> <out-dir> [k=v ...]
    mutants_matrix.py verdict <matrix.json> <allow-list>   the gate (exit 0 / 4 / 5)
    mutants_matrix.py check-allow <allow-list>             parse it, or exit non-zero

`collect` writes <out-dir>/matrix.json and <out-dir>/matrix.md. Trailing k=v
pairs (wall_secs, budget_secs, features, tool_version, budget_hit) are copied
into the JSON header.

The matrix (schema `ciris-persist/mutants-matrix/v1`):

    {
      "schema": ..., "tool": ..., "tool_version": ..., "scope": <path>,
      "test_filter": <filterset>, "features": ..., "wall_secs": N,
      "budget_secs": N, "complete": bool,
      "tests":   [<test name>, ...],        every witness the run executed
      "mutants": [{"id", "file", "line", "col", "description",
                   "outcome": caught|caught_out_of_scope|crashed|missed|
                              timeout|unviable|not_run,
                   "killed_by": [<test name>, ...]}, ...],
      "out_of_scope": [<description>, ...],  generated by the tool, outside every
                                             scope range, dropped from the matrix
      "summary": {"mutants", <one count per outcome>},
      "kills_per_test": {<test name>: N, ...},
      "tests_killing_nothing": [<test name>, ...],  ran, failed under no mutant
      "tests_never_run": [<test name>, ...]        the tool never ran it (mutest:
                                                   outside its static call graph)
    }

A mutant is `caught` when at least one witness failed under it. `killed_by`
lists every witness that failed, because the tools run with fail-fast off;
an empty `killed_by` on a `caught` mutant means it was caught by a crash or
a build failure the log does not attribute to one test (cargo-mutants).

mutest runs the WHOLE lib suite and the matrix keeps the scope's witnesses,
so a mutest outcome is read from the retained witnesses' rows:
`caught_out_of_scope` is a mutant only an out-of-scope test detected, and
`crashed` is a harness crash no test's row attributes.
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
SCHEMA = "ciris-persist/mutants-matrix/v1"
#: Every `outcome` a matrix can carry, in summary order. `caught_out_of_scope`
#: and `crashed` come only from mutest (see `mutest_outcome`).
OUTCOMES = ("caught", "caught_out_of_scope", "crashed", "missed", "timeout", "unviable", "not_run")


# ── scope files ─────────────────────────────────────────────────────────────


def parse_scope(path: str) -> dict:
    scope = {"tests": None, "witnesses": [], "entries": []}
    for n, raw in enumerate(Path(path).read_text().splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        if line.startswith("tests:"):
            scope["tests"] = line[len("tests:"):].strip()
            continue
        if line.startswith("witnesses:"):
            scope["witnesses"] += line[len("witnesses:"):].split()
            continue
        file, *fns = line.split()
        if not (REPO / file).is_file():
            raise SystemExit(f"{path}:{n}: no such file {file}")
        scope["entries"].append({"file": file, "fns": fns})
    if not scope["tests"]:
        raise SystemExit(f"{path}: no `tests:` line")
    if not scope["entries"]:
        raise SystemExit(f"{path}: no files")
    return scope


def _blank_literals(src: str) -> str:
    """The source with comments, strings and char literals blanked to spaces
    (newlines kept), so braces inside them cannot move a function's end."""
    out = list(src)
    i, n = 0, len(src)

    def blank(a: int, b: int) -> None:
        for k in range(a, min(b, n)):
            if out[k] != "\n":
                out[k] = " "

    while i < n:
        c = src[i]
        if src.startswith("//", i):
            j = src.find("\n", i)
            j = n if j < 0 else j
            blank(i, j)
            i = j
        elif src.startswith("/*", i):
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith("/*", j):
                    depth, j = depth + 1, j + 2
                elif src.startswith("*/", j):
                    depth, j = depth - 1, j + 2
                else:
                    j += 1
            blank(i, j)
            i = j
        elif (m := re.match(r'b?r(#*)"', src[i:i + 300])) and (i == 0 or not (src[i - 1].isalnum() or src[i - 1] == "_")):
            close = '"' + m.group(1)
            j = src.find(close, i + m.end())
            j = n if j < 0 else j + len(close)
            blank(i, j)
            i = j
        elif c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            blank(i, j + 1)
            i = j + 1
        elif c == "'" and (m := re.match(r"'(\\[^']{1,10}|[^\\'])'", src[i:i + 14])):
            blank(i, i + m.end())
            i += m.end()
        else:
            i += 1
    return "".join(out)


def fn_range(file: str, name: str) -> tuple[int, int]:
    """1-based inclusive line range of the one `fn <name>` body in `file`."""
    src = _blank_literals((REPO / file).read_text())
    hits = []
    for m in re.finditer(rf"\bfn\s+{re.escape(name)}\s*[<(]", src):
        # The body opens at the first `{` at paren/bracket depth 0; a `;`
        # first means a bodiless trait declaration.
        depth, j = 0, m.end() - 1
        while j < len(src):
            ch = src[j]
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif depth == 0 and ch == ";":
                j = -1
                break
            elif depth == 0 and ch == "{":
                break
            j += 1
        if j < 0:
            continue
        braces, k = 0, j
        while k < len(src):
            if src[k] == "{":
                braces += 1
            elif src[k] == "}":
                braces -= 1
                if braces == 0:
                    break
            k += 1
        start = src.count("\n", 0, m.start()) + 1
        hits.append((start, src.count("\n", 0, k) + 1))
    if len(hits) != 1:
        lines = ", ".join(str(h[0]) for h in hits) or "none"
        raise SystemExit(f"{file}: `fn {name}` must have exactly one body; found {len(hits)} (lines {lines})")
    return hits[0]


def _item_end(src: str, j: int) -> int:
    """Offset of the last character of the item that starts at or after `j`:
    the first `;` at paren/bracket depth 0, or the `}` closing the first `{`
    at that depth. `src` is already literal-blanked."""
    depth, n = 0, len(src)
    while j < n:
        ch = src[j]
        if ch in "([":
            depth += 1
        elif ch in ")]":
            depth -= 1
        elif depth == 0 and ch == ";":
            return j
        elif depth == 0 and ch == "{":
            braces = 0
            while j < n:
                if src[j] == "{":
                    braces += 1
                elif src[j] == "}":
                    braces -= 1
                    if braces == 0:
                        return j
                j += 1
            return n - 1
        j += 1
    return n - 1


def _top_level_args(pred: str) -> list[str]:
    out, depth, cur = [], 0, ""
    for ch in pred:
        if ch == "(":
            depth += 1
        elif ch == ")":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur.strip())
            cur = ""
        else:
            cur += ch
    if cur.strip():
        out.append(cur.strip())
    return out


def _test_only(pred: str) -> bool:
    """A `cfg` predicate that can hold only in a test build: `test`, or
    `all(..)` with `test` among its terms. `any(test, ..)` and `not(test)`
    can hold in a production build."""
    pred = re.sub(r"\s+", "", pred)
    if pred == "test":
        return True
    m = re.fullmatch(r"all\((.*)\)", pred)
    return bool(m) and any(_test_only(a) for a in _top_level_args(m.group(1)))


def test_gated_ranges(file: str) -> list[tuple[int, int]]:
    """1-based inclusive line ranges of the items in `file` that exist only
    in a test build: a `#[cfg(test)]` / `#[cfg(all(test, ..))]` item or
    statement, and any `mod` whose name contains `test_support`. Mutating
    them measures the tests, not the code under test (CIRISPersist#1051:
    two of the first nightly run's six survivors were field deletions inside
    `#[cfg(all(test, ..))] mod r2_test_support`, which cargo-mutants 27.1
    does not skip; it skips only a bare `#[cfg(test)]`)."""
    src = _blank_literals((REPO / file).read_text())
    if re.search(r"#!\[\s*cfg\s*\(\s*test\s*\)\s*\]", src):
        return [(1, src.count("\n") + 1)]
    out = []
    starts = []
    for m in re.finditer(r"#\[\s*cfg\s*\(", src):
        depth, j = 1, m.end()
        while j < len(src) and depth:
            depth += {"(": 1, ")": -1}.get(src[j], 0)
            j += 1
        if _test_only(src[m.end():j - 1]):
            starts.append((m.start(), src.index("]", j) + 1))
    for m in re.finditer(r"\bmod\s+\w*test_support\w*\b", src):
        starts.append((m.start(), m.start()))
    for a, j in starts:
        end = _item_end(src, j)
        out.append((src.count("\n", 0, a) + 1, src.count("\n", 0, end) + 1))
    merged: list[tuple[int, int]] = []
    for a, b in sorted(out):
        if merged and a <= merged[-1][1]:
            merged[-1] = (merged[-1][0], max(b, merged[-1][1]))
        else:
            merged.append((a, b))
    return merged


def _subtract(a: int, b: int, holes: list[tuple[int, int]]) -> list[tuple[int, int]]:
    segs = [(a, b)]
    for ha, hb in holes:
        nxt = []
        for x, y in segs:
            if hb < x or ha > y:
                nxt.append((x, y))
                continue
            if x < ha:
                nxt.append((x, ha - 1))
            if hb < y:
                nxt.append((hb + 1, y))
        segs = nxt
    return segs


def scope_ranges(scope: dict) -> list[tuple[str, int, int]]:
    """(file, first line, last line), with every test-only item removed
    (`test_gated_ranges`). A whole file runs to its last line."""
    out = []
    for e in scope["entries"]:
        file = e["file"]
        spans = [fn_range(file, fn) for fn in e["fns"]]
        if not e["fns"]:
            spans = [(1, (REPO / file).read_text().count("\n") + 1)]
        holes = test_gated_ranges(file)
        for a, b in spans:
            out += [(file, x, y) for x, y in _subtract(a, b, holes)]
    return out


def scope_diff(ranges) -> str:
    """The scope as a unified diff that ADDS exactly its lines, for
    cargo-mutants' `--in-diff`: one hunk per file, every in-scope line `+`,
    every other line context. cargo-mutants 27.1 applies neither `-F` nor
    `-E` to its struct-field deletions (CIRISPersist#1051: an `-F` of
    `check_capacity_consent_admission` still lists `delete field as_of` in
    four other functions and two in `r2_test_support`), so a name regex
    cannot bound the run; a diff does, by line."""
    out = []
    for file in sorted({f for f, _, _ in ranges}):
        lines = (REPO / file).read_text().split("\n")
        if lines and lines[-1] == "":
            lines.pop()
        added = set()
        for f, a, b in ranges:
            if f == file:
                added.update(range(a, b + 1))
        ctx = sum(1 for k in range(1, len(lines) + 1) if k not in added)
        out.append(f"diff --git a/{file} b/{file}\n--- a/{file}\n+++ b/{file}")
        out.append(f"@@ -{1 if ctx else 0},{ctx} +1,{len(lines)} @@")
        out += [("+" if k in added else " ") + t for k, t in enumerate(lines, 1)]
    return "\n".join(out) + "\n"


def in_scope(ranges, file: str, line: int) -> bool:
    return any(f == file and a <= line <= b for f, a, b in ranges)


def resolve(tool: str, scope_path: str, diff_out: str | None = None) -> None:
    scope = parse_scope(scope_path)
    ranges = scope_ranges(scope)
    if tool == "cargo-mutants":
        if diff_out is None:
            raise SystemExit("resolve cargo-mutants needs a <diff-out> path")
        Path(diff_out).write_text(scope_diff(ranges))
        for f in sorted({f for f, _, _ in ranges}):
            print("-f")
            print(f)
        print("--in-diff")
        print(diff_out)
    elif tool == "mutest":
        print(",".join(f"file:{f}:{a}..{b}" for f, a, b in ranges))
    else:
        raise SystemExit(f"unknown tool {tool!r}")


# ── collection ──────────────────────────────────────────────────────────────

#: nextest's per-test status lines: `        FAIL [   0.012s] (  3/120) ciris-persist mod::test`
#: (the `(n/m)` counter is absent on older nextest). Binary id, then test name.
NEXTEST_LINE = re.compile(
    r"^\s*(PASS|FAIL|TIMEOUT|SIGSEGV|SIGABRT|SIGKILL|SIGBUS|ABORT|LEAK-FAIL|FLAKY \d+/\d+)"
    r"\s+\[[^\]]*\]\s+(?:\(\s*\d+/\d+\)\s+)?(\S+)\s+(\S+)\s*$"
)


#: An SGR colour escape. The nightly job sets `CARGO_TERM_COLOR=always`, which
#: nextest honours inside cargo-mutants' logs: `\x1b[32;1m        PASS\x1b[0m
#: [ ...` matched NEXTEST_LINE nowhere, so the first scheduled run's matrix
#: listed 0 witnesses and credited no kill to any (CIRISPersist#1051).
ANSI = re.compile(r"\x1b\[[0-9;]*[A-Za-z]")


def _nextest_results(log: str) -> dict[str, str]:
    res = {}
    for line in ANSI.sub("", log).splitlines():
        m = NEXTEST_LINE.match(line)
        if m:
            res[m.group(3)] = m.group(1)
    return res


def collect_cargo_mutants(out_dir: Path, scope: dict) -> tuple[list, list, list]:
    ranges = scope_ranges(scope)
    mo = out_dir if (out_dir / "outcomes.json").exists() else out_dir / "mutants.out"
    outcomes = json.loads((mo / "outcomes.json").read_text())
    tests: set[str] = set()
    mutants, dropped = [], []
    summary_map = {
        "CaughtMutant": "caught", "MissedMutant": "missed", "Timeout": "timeout",
        "Unviable": "unviable", "Success": "missed", "Failure": "caught",
    }
    for i, o in enumerate(outcomes.get("outcomes", [])):
        scen = o.get("scenario")
        log_path = mo / o.get("log_path", "")
        log = log_path.read_text(errors="replace") if log_path.is_file() else ""
        results = _nextest_results(log)
        if scen == "Baseline":
            # A red baseline means no mutant was tested at all; an empty
            # matrix from it would read as "nothing to report".
            if o.get("summary") != "Success":
                raise SystemExit(f"baseline did not pass ({o.get('summary')}); see {log_path}")
            # A green baseline ran the scope's witnesses. Reading none of
            # them is the parser failing, not an empty scope: every count
            # after this would be a zero that cannot be anything else.
            if not results:
                raise SystemExit(f"no nextest result line read from the green baseline {log_path}")
            tests |= set(results)
            continue
        mut = (scen or {}).get("Mutant", {})
        file = mut.get("file", "")
        span = mut.get("span", {}).get("start", {})
        line, col = span.get("line", 0), span.get("column", 0)
        desc = f"{file}:{line}:{col}: {mut.get('name') or mut.get('replacement', '')}"
        name = mut.get("name")
        if name:
            desc = name if name.startswith(file) else f"{file}:{line}:{col}: {name}"
        if not in_scope(ranges, file, line):
            dropped.append(desc)
            continue
        tests |= set(results)
        killers = sorted(t for t, st in results.items() if st != "PASS" and not st.startswith("FLAKY"))
        mutants.append({
            "id": len(mutants) + 1, "file": file, "line": line, "col": col,
            "description": desc,
            "outcome": summary_map.get(o.get("summary", ""), "not_run"),
            "killed_by": killers,
        })
    # outcomes.json lists only the mutants that FINISHED. An interrupted run
    # (budget, OOM, a crashed session) leaves the rest out, and a matrix of
    # only the finished ones would read "complete". mutants.json is the
    # tool's full list: every in-scope mutant missing from outcomes is
    # not_run, which marks the matrix INCOMPLETE.
    listed = mo / "mutants.json"
    if listed.is_file():
        seen = {m["description"] for m in mutants} | set(dropped)
        for mut in json.loads(listed.read_text()):
            file = mut.get("file", "")
            span = mut.get("span", {}).get("start", {})
            line, col = span.get("line", 0), span.get("column", 0)
            name = mut.get("name") or ""
            desc = name if name.startswith(file) else f"{file}:{line}:{col}: {name}"
            if desc in seen:
                continue
            if not in_scope(ranges, file, line):
                dropped.append(desc)
                continue
            mutants.append({
                "id": len(mutants) + 1, "file": file, "line": line, "col": col,
                "description": desc, "outcome": "not_run", "killed_by": [],
            })
    # nextest runs every filtered witness under every mutant: none is unreached.
    return sorted(tests), mutants, dropped, []


def mutest_outcome(flag: str, kept: dict[str, str], cell: dict[str, str], code: dict) -> str:
    """One mutant's outcome from the RETAINED witnesses' cells.

    mutest's `overall_detections` flag is over the whole lib suite, and the
    matrix keeps only the scope's witnesses: copying the flag labelled a
    mutant `caught` that only an out-of-scope test detected, with an empty
    killer list (Codex on PR #1039). So:

    - `caught`: a retained witness detected it (`D`) or crashed under it (`C`);
    - `timeout`: a retained witness timed out and none detected it;
    - `crashed`: the harness crashed (`C`) and no test's row attributes it;
    - `caught_out_of_scope`: detected, but by no retained witness;
    - otherwise mutest's flag: `missed`, or `not_run`.
    """
    kept_codes = set(kept.values())
    if kept_codes & {"D", "C"}:
        return "caught"
    if "T" in kept_codes:
        return "timeout"
    attributed = any(c in "DTC" for c in cell.values())
    if flag == "C" and not attributed:
        return "crashed"
    if flag in "DTC" or attributed:
        return "caught_out_of_scope"
    return code.get(flag, "not_run")


def collect_mutest(json_dir: Path, scope: dict) -> tuple[list, list, list]:
    ranges = scope_ranges(scope)
    lib = next(json_dir.rglob("evaluation.json")).parent
    muts = json.loads((lib / "mutations.json").read_text())["mutations"]
    ev = json.loads((lib / "evaluation.json").read_text())
    run = ev["mutation_runs"][0]
    names = [t["name"] for t in ev["tests"]]
    # mutest's harness runs the whole lib suite; keep the scope's witnesses.
    # Only the `test(/<regex>/)` filterset form is translated.
    m = re.fullmatch(r"test\(/(.*)/\)", scope["tests"])
    keep = {t for t in names if m is None or re.search(m.group(1), t)}
    overall = run["mutation_detection_matrix"]["overall_detections"]
    per_test = run["mutation_detection_matrix"]["test_detections"]
    code = {"D": "caught", "-": "missed", "T": "timeout", "C": "caught", ".": "not_run"}
    mutants, dropped = [], []
    for k, m in enumerate(sorted(muts, key=lambda m: m["mutation_id"])):
        span = m["origin_span"]
        file, (line, col) = span["path"], span["begin"]
        desc = f"{file}:{line}:{col}: {m['display_name']} [{m['mutation_op']}]"
        if not in_scope(ranges, file, line):
            dropped.append(desc)
            continue
        idx = m["mutation_id"] - 1
        flag = overall[idx] if idx < len(overall) else "."
        cell = {names[t]: (row[idx] if idx < len(row) else ".") for t, row in enumerate(per_test)}
        kept = {t: c for t, c in cell.items() if t in keep}
        killers = sorted(t for t, c in kept.items() if c in "DTC")
        mutants.append({
            "id": len(mutants) + 1, "file": file, "line": line, "col": col,
            "description": desc, "outcome": mutest_outcome(flag, kept, cell, code),
            "killed_by": killers,
        })
    # mutest runs a test only under mutants its static call graph says the
    # test reaches. A witness whose row is all `.` was never run: it killed
    # nothing because it was never asked, which is a tool limit, not a verdict.
    ran = {names[t] for t, row in enumerate(per_test) if any(c != "." for c in row)}
    return sorted(keep), mutants, dropped, sorted(keep - ran)


def write_matrix(tool, scope_path, scope, tests, mutants, dropped, unreached, out: Path, extra: dict) -> dict:
    out.mkdir(parents=True, exist_ok=True)
    pattern = scope["tests"]
    kills = {t: 0 for t in tests}
    for m in mutants:
        for t in m["killed_by"]:
            kills[t] = kills.get(t, 0) + 1
    summary = {"mutants": len(mutants)}
    for k in OUTCOMES:
        summary[k] = sum(1 for m in mutants if m["outcome"] == k)
    budget_hit = extra.pop("budget_hit", "0") not in ("0", "", "false")
    matrix = {
        "schema": SCHEMA, "tool": tool, "scope": scope_path, "test_filter": pattern,
        **{k: (int(v) if k.endswith("_secs") and str(v).isdigit() else v) for k, v in extra.items()},
        "complete": not budget_hit and summary["not_run"] == 0,
        "tests": tests, "mutants": mutants, "out_of_scope": dropped,
        "summary": summary, "kills_per_test": dict(sorted(kills.items())),
        "tests_killing_nothing": sorted(t for t, n in kills.items() if n == 0 and t not in unreached),
        "tests_never_run": unreached,
    }
    (out / "matrix.json").write_text(json.dumps(matrix, indent=2) + "\n")

    md = [f"# Mutation matrix — `{scope_path}`", ""]
    md.append(f"Tool `{tool}` {matrix.get('tool_version', '')}; witnesses `{pattern}`; "
              f"features `{matrix.get('features', '')}`; wall {matrix.get('wall_secs', '?')}s "
              f"of a {matrix.get('budget_secs', '?')}s budget; "
              f"{'complete' if matrix['complete'] else 'INCOMPLETE'}.")
    md += ["", "| mutants | " + " | ".join(k.replace("_", " ") for k in OUTCOMES) + " |",
           "|---:" * (len(OUTCOMES) + 1) + "|",
           "| " + " | ".join(str(summary[k]) for k in ("mutants", *OUTCOMES)) + " |", ""]
    md += ["## Mutants", "", "| # | site | outcome | killed by |", "|---:|---|---|---|"]
    for m in mutants:
        site = m["description"].replace("|", "\\|").replace("`", "'")
        short = ", ".join(t.rsplit("::", 2)[-2] + "::" + t.rsplit("::", 1)[-1] if t.count("::") >= 2 else t
                          for t in m["killed_by"]) or "—"
        md.append(f"| {m['id']} | `{site}` | {m['outcome'].upper() if m['outcome'] == 'missed' else m['outcome']} | {short} |")
    md += ["", "## Kills per witness", "", "| witness | mutants killed |", "|---|---:|"]
    for t, n in matrix["kills_per_test"].items():
        note = " (never run by the tool)" if t in unreached else (" **(none)**" if n == 0 else "")
        md.append(f"| `{t}` | {n}{note} |")
    if dropped:
        md += ["", f"## Generated outside the scope ({len(dropped)}, dropped)", ""]
        md += [f"- `{d}`" for d in dropped]
    (out / "matrix.md").write_text("\n".join(md) + "\n")
    return matrix


# ── the verdict ─────────────────────────────────────────────────────────────

#: Outcomes that are a surviving mutant for the gate: no witness in the scope
#: went red (`missed`), only a test outside it did (`caught_out_of_scope`),
#: or the run hung until the tool's own timeout (`timeout`: detected, but a
#: bound is missing and no witness is credited, and each one costs minutes of
#: the budget).
SURVIVING = ("missed", "caught_out_of_scope", "timeout")

ALLOW_LINE = re.compile(r"^(?P<file>[^\s:]+\.rs)(?::(?P<line>\d+))?\s+(?P<desc>.+?)\s+#(?P<issue>\d+)\b(?P<why>.*)$")
SITE = re.compile(r"^(?P<file>[^:]+):(?P<line>\d+):(?P<col>\d+):\s*(?P<desc>.*)$")


def parse_allow_list(path: str) -> list[dict]:
    """`<file>[:<line>] <the tool's mutation text> #<issue> [why]`, one per
    line, `#` at the start of a line a comment. The mutation text is the
    tool's own (`replace > with >= in Counters::snapshot`), compared exactly;
    with a line number the line must match too. A line that does not parse,
    or names no tracking issue, is a refusal: an allow-list entry nobody can
    trace is a survivor nobody owns."""
    out = []
    for n, raw in enumerate(Path(path).read_text().splitlines(), 1):
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        m = ALLOW_LINE.match(line)
        if not m:
            raise SystemExit(f"{path}:{n}: not `<file>[:<line>] <mutation> #<issue>`: {raw!r}")
        out.append({"file": m["file"], "line": int(m["line"]) if m["line"] else None,
                    "desc": m["desc"], "issue": int(m["issue"]), "why": m["why"].strip(" —-"),
                    "at": f"{path}:{n}"})
    return out


def _allowed(mutant: dict, allow: list[dict]) -> dict | None:
    m = SITE.match(mutant["description"])
    desc = m["desc"] if m else mutant["description"]
    for a in allow:
        if a["file"] == mutant["file"] and a["desc"] == desc and a["line"] in (None, mutant["line"]):
            return a
    return None


def _escape(text: str) -> str:
    """A workflow-command message: `%`, CR and LF must be escaped."""
    return text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")


def verdict(matrix: dict, allow: list[dict], repo_url: str = "") -> tuple[int, list[str], list[str]]:
    """(exit code, workflow-command annotations, step-summary markdown).

    0: complete, and every surviving mutant is allow-listed with an issue.
    4: INCOMPLETE (budget hit, or a mutant the tool never ran): the job must
       not read green while mutants went untested (CIRISPersist#1051, run 1:
       rc 124, 8 of 85 untested, job green).
    5: a surviving mutant that no allow-list entry names. Wins over 4."""
    s = matrix["summary"]
    label = matrix["scope"] + (f" (shard {matrix['shard']})" if matrix.get("shard") else "")
    ann, md = [], [f"## Mutants — `{label}`", ""]
    md.append(f"`{matrix['tool']}` {matrix.get('tool_version', '')}: {s['mutants']} mutants, "
              f"wall {matrix.get('wall_secs', '?')} s of a {matrix.get('budget_secs', '?')} s budget, "
              f"tool exit {matrix.get('tool_rc', '?')}.")
    md += ["", "| " + " | ".join(k.replace("_", " ") for k in OUTCOMES) + " |",
           "|---:" * len(OUTCOMES) + "|", "| " + " | ".join(str(s[k]) for k in OUTCOMES) + " |", ""]
    rc = 0
    if not matrix["complete"]:
        rc = 4
        why = (f"budget hit (tool exit {matrix.get('tool_rc')})" if str(matrix.get("tool_rc")) == "124"
               else "the tool stopped early")
        msg = (f"INCOMPLETE: {s['not_run']} of {s['mutants']} mutants never tested; {why}. "
               "Shard the scope or raise the budget (docs/MUTATION_TESTING.md).")
        ann.append(f"::error title=mutants {label} INCOMPLETE::{_escape(msg)}")
        md += [f"**{msg}**", ""]
    unlisted, listed = [], []
    for m in matrix["mutants"]:
        if m["outcome"] not in SURVIVING:
            continue
        a = _allowed(m, allow)
        (listed if a else unlisted).append((m, a))
    if unlisted:
        rc = 5
    if unlisted or listed:
        md += ["| site | outcome | allowed by |", "|---|---|---|"]
    for m, a in unlisted + listed:
        site = m["description"].replace("|", "\\|").replace("`", "'")
        if a:
            ref = f"[#{a['issue']}]({repo_url}/issues/{a['issue']})" if repo_url else f"#{a['issue']}"
            md.append(f"| `{site}` | {m['outcome']} | {ref} |")
            ann.append(f"::warning file={m['file']},line={m['line']},title=Allowed surviving mutant (#{a['issue']})::"
                       + _escape(m["description"]))
        else:
            md.append(f"| `{site}` | **{m['outcome'].upper()}** | **not allow-listed** |")
            ann.append(f"::error file={m['file']},line={m['line']},title=Surviving mutant ({m['outcome']}), not allow-listed::"
                       + _escape(m["description"] + " — kill it with a witness, or list it in "
                                 "scripts/mutants/allowed_survivors.txt with its tracking issue"))
    if not unlisted and not listed:
        md.append("No surviving mutant.")
    verdict_word = {0: "PASS", 4: "FAIL (incomplete)", 5: "FAIL (unlisted survivors)"}[rc]
    md += ["", f"Verdict: **{verdict_word}** ({len(unlisted)} unlisted, {len(listed)} allow-listed survivors)."]
    return rc, ann, md


def main(argv: list[str]) -> int:
    if len(argv) >= 3 and argv[1] == "tests":
        print(parse_scope(argv[2])["tests"])
        return 0
    if len(argv) in (4, 5) and argv[1] == "resolve":
        resolve(argv[2], argv[3], argv[4] if len(argv) == 5 else None)
        return 0
    if len(argv) >= 6 and argv[1] == "collect":
        tool, raw, scope_path, out = argv[2], Path(argv[3]), argv[4], Path(argv[5])
        extra = dict(a.split("=", 1) for a in argv[6:])
        scope = parse_scope(scope_path)
        if tool == "cargo-mutants":
            tests, mutants, dropped, unreached = collect_cargo_mutants(raw, scope)
        elif tool == "mutest":
            tests, mutants, dropped, unreached = collect_mutest(raw, scope)
        else:
            raise SystemExit(f"unknown tool {tool!r}")
        m = write_matrix(tool, scope_path, scope, tests, mutants, dropped, unreached, out, extra)
        s = m["summary"]
        print(f"matrix: {s['mutants']} mutants, {s['caught']} caught, "
              f"{s['caught_out_of_scope']} caught out of scope, {s['crashed']} crashed, {s['missed']} missed, "
              f"{s['timeout']} timeout, {s['unviable']} unviable, {s['not_run']} not run; "
              f"{len(m['tests'])} witnesses, {len(m['tests_killing_nothing'])} killed nothing, "
              f"{len(unreached)} never run "
              f"-> {out}/matrix.json")
        return 0
    if len(argv) == 3 and argv[1] == "check-allow":
        parse_allow_list(argv[2])
        return 0
    if len(argv) == 4 and argv[1] == "verdict":
        import os
        matrix = json.loads(Path(argv[2]).read_text())
        url = f"{os.environ.get('GITHUB_SERVER_URL', '')}/{os.environ['GITHUB_REPOSITORY']}" \
            if os.environ.get("GITHUB_REPOSITORY") else ""
        rc, ann, md = verdict(matrix, parse_allow_list(argv[3]), url)
        for a in ann:
            print(a)
        print("\n".join(md))
        if os.environ.get("GITHUB_STEP_SUMMARY"):
            with open(os.environ["GITHUB_STEP_SUMMARY"], "a") as f:
                f.write("\n".join(md) + "\n\n")
        return rc
    print(__doc__, file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
