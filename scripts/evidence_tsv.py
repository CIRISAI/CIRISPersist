#!/usr/bin/env python3
"""evidence_tsv.py — evidence/cc_impl.tsv is GENERATED from the manifest
(CIRISPersist#1052).

    scripts/evidence_tsv.py write    regenerate evidence/cc_impl.tsv
    scripts/evidence_tsv.py check    exit 1, with a diff, if the committed file differs
    scripts/evidence_tsv.py print    the generated text on stdout

The source is `namespace_supersets.json` → `evidence_export.CIRISPersist`: one
row per entry whose `tsv_target` is `evidence/cc_impl.tsv`, in the export's
order. An entry with `tsv_target: "n/a"` must say why in `tsv_excluded`; an
entry's `tsv_comment_before` (blank or `#` lines) is written above its row.

The version column is derived, not data. A row citing this crate's sources
(`src/…`) pins `ciris-persist@<Cargo.toml version>`, so a version bump changes
the generated file exactly as release.sh's re-stamp does. Any other row (a
cross-repo citation) pins the entry's own `crate`, the version of the crate
that defines the symbol, which is not ours to stamp.

WHY. The cc-conformance attestation (#1028) signs this file, and until v54.1.0
it was edited by hand. 131 of its 174 rows existed only in the tsv, so the
manifest and the signed registry could drift with nothing to compare them
(#1052, found re-pointing two citations under #1026).
"""
from __future__ import annotations

import difflib
import json
import os
import re
import sys
from pathlib import Path

TARGET = "evidence/cc_impl.tsv"
MANIFEST_REL = "src/federation/namespace/namespace_supersets.json"

HEADER = """\
# CIRIS evidence registry — impl:CIRISPersist tier (CIRISConstitution#17 / CIRISPersist#519)
# The sibling spec-map the Constitution's check_evidence.py resolves CIRISPersist#nsproc
# pointers against: every path#symbol MUST resolve at the pinned crate version.
# CODE-VERIFIED (the evidence_cc_impl_pointers_resolve witness re-checks every src/ row).
# GENERATED by scripts/evidence_tsv.py from namespace_supersets.json
# evidence_export[CIRISPersist]; edit the manifest, then `scripts/evidence_tsv.py write`
# (CIRISPersist#1052). src/ rows pin this crate's Cargo.toml version.
# persist's half of the #519 item-6 field_processor_matrix → CLM-nsproc citation loop.
# Columns: decimal_id, claim_id, repo, path#symbol, crate@version
decimal_id\tclaim_id\trepo\tpath#symbol\tcrate@version
"""


def crate_version(cargo_toml: str) -> str:
    m = re.search(r'(?ms)^\[package\]\s*$.*?^version\s*=\s*"([^"]+)"', cargo_toml)
    if not m:
        raise SystemExit("Cargo.toml: no [package] version")
    return m.group(1)


def generate(manifest: dict, version: str) -> str:
    rows, seen = [], set()
    for n, e in enumerate(manifest["evidence_export"]["CIRISPersist"]):
        where = f"evidence_export.CIRISPersist[{n}] ({e.get('claim_id')})"
        tgt = e.get("tsv_target")
        if tgt == "n/a":
            if not e.get("tsv_excluded"):
                raise SystemExit(f"{where}: tsv_target n/a needs a tsv_excluded reason")
            continue
        if tgt != TARGET:
            raise SystemExit(f"{where}: tsv_target {tgt!r} is neither {TARGET!r} nor 'n/a'")
        path = e["path#symbol"]
        if "\t" in path or "#" not in path:
            raise SystemExit(f"{where}: path#symbol {path!r} is not a path#symbol")
        stamp = f"ciris-persist@{version}" if path.startswith("src/") else e.get("crate")
        if not stamp:
            raise SystemExit(f"{where}: a cross-repo row needs its own `crate` stamp")
        row = (e["decimal_id"], e["claim_id"], e["repo"], path, stamp)
        if row in seen:
            raise SystemExit(f"{where}: duplicate row {row}")
        seen.add(row)
        # Free text the registry carries between rows (a section note) rides
        # on the entry it precedes: a blank line or `#` lines only.
        before = e.get("tsv_comment_before") or []
        if any(line and not line.startswith("#") for line in before):
            raise SystemExit(f"{where}: tsv_comment_before holds a non-comment line")
        rows += before
        rows.append("\t".join(row))
    return HEADER + "\n".join(rows) + "\n"


def data_rows(text: str) -> int:
    return sum(1 for line in text.splitlines()
               if line and not line.startswith("#") and not line.startswith("decimal_id\t"))


def main(argv: list[str]) -> int:
    if len(argv) != 2 or argv[1] not in ("write", "check", "print"):
        print(__doc__, file=sys.stderr)
        return 2
    # EVIDENCE_TSV_ROOT: a fixture tree for scripts/evidence_tsv_test.py.
    root = Path(os.environ.get("EVIDENCE_TSV_ROOT") or Path(__file__).resolve().parent.parent)
    tsv = root / TARGET
    text = generate(json.loads((root / MANIFEST_REL).read_text()),
                    crate_version((root / "Cargo.toml").read_text()))
    if argv[1] == "print":
        sys.stdout.write(text)
    elif argv[1] == "write":
        tsv.write_text(text)
        print(f"wrote {TARGET}: {data_rows(text)} rows")
    else:
        have = tsv.read_text()
        if have != text:
            sys.stdout.writelines(difflib.unified_diff(
                have.splitlines(True), text.splitlines(True),
                "evidence/cc_impl.tsv (committed)", "evidence/cc_impl.tsv (generated)"))
            print("EVIDENCE TSV DRIFT: evidence/cc_impl.tsv differs from what "
                  "namespace_supersets.json generates; edit the manifest, then "
                  "`scripts/evidence_tsv.py write` (CIRISPersist#1052)")
            return 1
        print(f"evidence/cc_impl.tsv matches the manifest ({data_rows(text)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
